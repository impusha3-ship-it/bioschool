import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

/*
  Ни один тип заданий настоящей работы не должен пропасть с сайта.

  Решение учителя от 31 августа 2026 года: тип задания, впервые увиденный
  учеником на самой работе, стоит ему баллов независимо от того, знает он
  биологию или нет. Значит, каждый из двадцати восьми типов образца ФИОКО
  обязан встретиться в уроках хотя бы раз.

  Сейчас закрыта меньшая половина, и красный тест пользы бы не принёс. Поэтому
  список незакрытых заведён честно и целиком — а работа состоит в том, чтобы
  вычёркивать из него строки. Уменьшаться он может, расти — нет: за этим следит
  ПОТОЛОК ниже.
*/

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/*
  Типы, которых на сайте ещё нет. Закрыв тип, удали его отсюда и уменьши
  ПОТОЛОК на столько же строк. Обратное не пройдёт: новую строку сюда не
  добавить, потому что ПОТОЛОК её не пустит.
*/
const ЕЩЁ_НЕ_ЗАКРЫТЫ = [
  '1.2', '2.2', '4.1', '4.2', '5.2', '7', '8',
  '11', '12.1', '13', '15.1', '15.2', '16.1', '16.2', '17', '18', '19',
];

const ПОТОЛОК = 17;

async function всеЗадания() {
  const dir = join(ROOT, 'content', 'lessons');
  const задания = [];
  for (const file of (await readdir(dir)).filter((f) => f.endsWith('.json'))) {
    const lesson = JSON.parse(await readFile(join(dir, file), 'utf8'));
    for (const q of lesson.vpr ?? []) задания.push({ file, где: 'тренажёр', q });
    for (const q of lesson.homework?.questions ?? []) задания.push({ file, где: 'домашка', q });
  }
  return задания;
}

const типы = JSON.parse(await readFile(join(ROOT, 'content', 'vpr-tipy.json'), 'utf8'));
const задания = await всеЗадания();
const встречается = new Set(задания.map((з) => з.q.vprType).filter(Boolean));

test('список типов совпадает с образцом работы', () => {
  assert.equal(типы.types.length, 28, 'в образце ФИОКО 2026 года двадцать восемь типов заданий');

  // Сумма баллов по типам — это максимальный первичный балл за работу.
  // Если она разошлась с 43, значит балл у какого-то типа записан неверно.
  const сумма = типы.types.reduce((s, т) => s + т.maxScore, 0);
  assert.equal(сумма, 43, 'сумма баллов по типам должна давать максимальный балл за работу');

  const номера = типы.types.map((т) => т.id);
  assert.equal(new Set(номера).size, номера.length, 'номер типа повторяется');

  const способы = new Set(Object.keys(типы.answerModes));
  for (const т of типы.types) {
    assert.ok(способы.has(т.answer), `тип ${т.id}: неизвестный способ ответа «${т.answer}»`);
    assert.ok(т.title && т.asks, `тип ${т.id}: нет названия или описания`);
  }
});

test('у каждого задания настоящей работы проставлен тип', () => {
  const без = задания.filter((з) => з.q.source && !з.q.vprType);
  assert.deepEqual(
    без.map((з) => `${з.file} / ${з.q.id}`),
    [],
    'у задания есть источник, но нет vprType — тип обязан стоять рядом с источником',
  );
});

test('проставленные типы существуют в списке', () => {
  const известные = new Set([
    ...типы.types.map((т) => т.id),
    ...типы.legacyTypes.map((т) => т.id),
  ]);
  const чужие = задания
    .filter((з) => з.q.vprType && !известные.has(з.q.vprType))
    .map((з) => `${з.file} / ${з.q.id}: «${з.q.vprType}»`);

  assert.deepEqual(чужие, [], 'такого типа нет ни в списке образца, ни в списке старых');
});

test('список незакрытых типов может только уменьшаться', () => {
  assert.ok(
    ЕЩЁ_НЕ_ЗАКРЫТЫ.length <= ПОТОЛОК,
    `в списке незакрытых ${ЕЩЁ_НЕ_ЗАКРЫТЫ.length} типов при потолке ${ПОТОЛОК}: ` +
      'новый тип в список не добавляют — его закрывают заданием',
  );

  const номера = new Set(типы.types.map((т) => т.id));
  for (const id of ЕЩЁ_НЕ_ЗАКРЫТЫ) {
    assert.ok(номера.has(id), `в списке незакрытых стоит «${id}», а такого типа в образце нет`);
  }
});

test('типы, объявленные закрытыми, действительно встречаются в уроках', () => {
  const обещаны = типы.types.map((т) => т.id).filter((id) => !ЕЩЁ_НЕ_ЗАКРЫТЫ.includes(id));
  const пусто = обещаны.filter((id) => !встречается.has(id));

  assert.deepEqual(
    пусто,
    [],
    'тип не числится незакрытым, но ни одного задания такого типа в уроках нет',
  );
});

test('закрытый тип вычеркнут из списка незакрытых', () => {
  const лишние = ЕЩЁ_НЕ_ЗАКРЫТЫ.filter((id) => встречается.has(id));

  assert.deepEqual(
    лишние,
    [],
    'задание такого типа уже есть — вычеркни его из ЕЩЁ_НЕ_ЗАКРЫТЫ и уменьши ПОТОЛОК',
  );
});
