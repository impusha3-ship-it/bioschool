import { test } from 'node:test';
import assert from 'node:assert/strict';
import { итог, ПУСТО } from '../../js/progress/core.js';
import { предыдущая as предыдущаяНеделя } from '../../js/progress/weeks.js';

const ДАТА = new Date(2026, 7, 18);

const КУРС = {
  grade: 5,
  sections: [
    { id: 'nauka', title: 'Наука', lessons: [{ id: 'у1' }, { id: 'у2' }] },
    { id: 'kletka', title: 'Клетка', lessons: [{ id: 'у3' }] },
  ],
};

function состояние(lessons = {}, weeks = {}) {
  return { ...ПУСТО, lessons, weeks };
}

function значок(итоги, id) {
  return итоги.значки.find((з) => з.id === id);
}

test('без баллов не выдан ни один значок', () => {
  const итоги = итог(состояние(), [КУРС], ДАТА);
  assert.equal(итоги.значки.every((з) => !з.есть), true);
});

test('первый балл выдаёт «Первый шаг»', () => {
  const итоги = итог(состояние({ у1: { game0: 10 } }), [КУРС], ДАТА);
  assert.equal(значок(итоги, 'first').есть, true);
});

test('«Без ошибок» — за чистую игру, а не за пройденную', () => {
  assert.equal(значок(итог(состояние({ у1: { game0: 10 } }), [КУРС], ДАТА), 'clean-game').есть, false);
  assert.equal(значок(итог(состояние({ у1: { game0: 15 } }), [КУРС], ДАТА), 'clean-game').есть, true);
});

test('«Ботаник» даётся за определитель, а не за игру', () => {
  assert.equal(значок(итог(состояние({ у1: { game0: 15 } }), [КУРС], ДАТА), 'botanist').есть, false);
  assert.equal(значок(итог(состояние({ у1: { key0: 15 } }), [КУРС], ДАТА), 'botanist').есть, true);
});

test('«Чистая работа» — за лабораторную без промахов', () => {
  assert.equal(значок(итог(состояние({ у1: { lab: 15 } }), [КУРС], ДАТА), 'clean-lab').есть, false);
  assert.equal(значок(итог(состояние({ у1: { lab: 20 } }), [КУРС], ДАТА), 'clean-lab').есть, true);
});

test('«Все пять» — за полный блок ВПР', () => {
  assert.equal(значок(итог(состояние({ у1: { vpr: 8 } }), [КУРС], ДАТА), 'vpr-full').есть, false);
  assert.equal(значок(итог(состояние({ у1: { vpr: 10 } }), [КУРС], ДАТА), 'vpr-full').есть, true);
});

test('«Месяц подряд» — четыре недели', () => {
  const три = { '2026-W32': 1, '2026-W33': 1, '2026-W34': 1 };
  const четыре = { '2026-W31': 1, ...три };
  assert.equal(значок(итог(состояние({}, три), [КУРС], ДАТА), 'month').есть, false);
  assert.equal(значок(итог(состояние({}, четыре), [КУРС], ДАТА), 'month').есть, true);
});

test('«Раздел закрыт» считает закрытые разделы', () => {
  const итоги = итог(состояние({ у1: { done: true }, у2: { done: true } }), [КУРС], ДАТА);
  assert.equal(значок(итоги, 'section').есть, true);
  assert.equal(значок(итоги, 'section').счёт, '1 из 2');
});

test('незакрытый до конца раздел не считается', () => {
  const итоги = итог(состояние({ у1: { done: true } }), [КУРС], ДАТА);
  assert.equal(значок(итоги, 'section').есть, false);
});

test('«Год закрыт» — все уроки курса', () => {
  const все = { у1: { done: true }, у2: { done: true }, у3: { done: true } };
  assert.equal(значок(итог(состояние(все), [КУРС], ДАТА), 'year').есть, true);
});

test('итог собирает баллы, ступень, серию и уроки', () => {
  const итоги = итог(
    состояние({ у1: { game0: 15, done: true }, у2: { vpr: 10 } }, { '2026-W34': 25 }),
    [КУРС],
    ДАТА,
  );
  assert.equal(итоги.xp, 25);
  assert.equal(итоги.ступень.имя, 'Наблюдатель');
  assert.equal(итоги.серия, 1);
  assert.deepEqual(итоги.уроки, {
    пройдено: 1,
    всего: 3,
    разделы: [
      { id: 'nauka', title: 'Наука', пройдено: 1, всего: 2 },
      { id: 'kletka', title: 'Клетка', пройдено: 0, всего: 1 },
    ],
  });
});

test('без курса итог всё равно считается', () => {
  const итоги = итог(состояние({ у1: { game0: 15, done: true } }), [], ДАТА);
  assert.equal(итоги.xp, 15);
  assert.equal(итоги.уроки.всего, 0);
  assert.equal(значок(итоги, 'year').есть, false);
});

test('пустой раздел не считается закрытым сам собой', () => {
  const курсСПустым = {
    grade: 5,
    sections: [
      { id: 'a', title: 'A', lessons: [{ id: 'у1' }] },
      { id: 'empty', title: 'Пусто', lessons: [] },
    ],
  };
  const итоги = итог(состояние({ у1: { done: true } }), [курсСПустым], ДАТА);
  // Закрыт только раздел 'a'; пустой раздел не даёт второй закрытый бесплатно.
  assert.equal(значок(итоги, 'section').счёт, '1 из 2');
});

test('курс без разделов не роняет итог', () => {
  const итоги = итог(состояние({ у1: { done: true } }), [{ grade: 5, sections: [] }], ДАТА);
  assert.deepEqual(итоги.уроки, { пройдено: 1, всего: 0, разделы: [] });
});

test('урок, которого нет в курсе, не роняет итог', () => {
  const итоги = итог(состояние({ уЧужой: { done: true }, у1: { done: true } }), [КУРС], ДАТА);
  assert.equal(итоги.уроки.всего, 3);
  assert.equal(итоги.уроки.разделы[0].пройдено, 1);
});

test('«Год закрыт» — если курсов два и закрыт только один', () => {
  const курсA = { grade: 5, sections: [{ id: 'a', title: 'A', lessons: [{ id: 'у1' }] }] };
  const курсB = { grade: 6, sections: [{ id: 'b', title: 'B', lessons: [{ id: 'у2' }] }] };
  const итоги = итог(состояние({ у1: { done: true } }), [курсA, курсB], ДАТА);
  assert.equal(значок(итоги, 'year').есть, true);
});

test('пустой курс не выдаёт «Год закрыт»', () => {
  // every() на пустом списке истинно: класс, до которого ещё не написано ни
  // одного урока, без этой защиты выдавал бы значок за ничто.
  const итоги = итог(состояние(), [{ grade: 6, sections: [] }], ДАТА);
  assert.equal(значок(итоги, 'year').есть, false);
});

test('«Четверть подряд» — восемь недель, а не четыре', () => {
  // Порог соседнего значка — 4, и скопировать его сюда по невнимательности
  // проще всего именно здесь. Без этого теста ошибка выдала бы значок вдвое
  // раньше, а отбирать выданное хуже, чем не выдать вовремя.
  const недели = (сколько) => {
    const weeks = {};
    let id = '2026-W34';
    for (let i = 0; i < сколько; i += 1) {
      weeks[id] = 1;
      id = предыдущаяНеделя(id);
    }
    return weeks;
  };

  assert.equal(значок(итог(состояние({}, недели(7)), [КУРС], ДАТА), 'quarter').есть, false);
  assert.equal(значок(итог(состояние({}, недели(8)), [КУРС], ДАТА), 'quarter').есть, true);
});

// ── Значки, добавленные 3 сентября ───────────────────────────

/*
  «Урок на отлично» проверяет не сумму, а каждый вид работы в отдельности:
  урок, где игра пройдена чисто, а блок ВПР решён наполовину, суммой мог бы
  обогнать урок, сделанный ровно, — и значок ушёл бы не тому.
*/
test('«Урок на отлично» требует максимума по каждому виду', () => {
  const идеал = { game0: 15, vpr: 10, done: true };
  assert.equal(значок(итог(состояние({ у1: идеал }), [КУРС], ДАТА), 'lesson-perfect').есть, true);

  const впрНеполный = { ...идеал, vpr: 8 };
  assert.equal(значок(итог(состояние({ у1: впрНеполный }), [КУРС], ДАТА), 'lesson-perfect').есть, false);

  const играСОшибкой = { ...идеал, game0: 10 };
  assert.equal(значок(итог(состояние({ у1: играСОшибкой }), [КУРС], ДАТА), 'lesson-perfect').есть, false);
});

// Уроки разные: где-то есть лабораторная, где-то нет. Требовать её у всех —
// значит закрыть значок для большинства уроков навсегда.
test('«Урок на отлично» не требует того, чего в уроке нет', () => {
  const безЛабы = { game0: 15, vpr: 10, done: true };
  assert.equal(значок(итог(состояние({ у1: безЛабы }), [КУРС], ДАТА), 'lesson-perfect').есть, true);

  const сЛабой = { ...безЛабы, lab: 15 };
  assert.equal(значок(итог(состояние({ у1: сЛабой }), [КУРС], ДАТА), 'lesson-perfect').есть, false,
    'лабораторная есть, но сделана не чисто');
});

/*
  Домашка в значок не входит, и это решение, а не недосмотр. Сдать её можно
  один раз и только если учитель задал урок этому классу: одна работа на 89
  закрыла бы значок по этому уроку навсегда, а гость не получил бы его вовсе.
  Объяснить ребёнку такую пропажу было бы нечем.
*/
test('домашка на «Урок на отлично» не влияет', () => {
  const слабаяДомашка = { game0: 15, vpr: 10, homework: 20, done: true };
  assert.equal(значок(итог(состояние({ у1: слабаяДомашка }), [КУРС], ДАТА), 'lesson-perfect').есть, true);
});

// Незаконченный урок не может быть «на отлично»: ученик мог взять одну игру
// на максимум и не притронуться к остальному.
test('«Урок на отлично» не даётся за незаконченный урок', () => {
  const начат = { game0: 15 };
  assert.equal(значок(итог(состояние({ у1: начат }), [КУРС], ДАТА), 'lesson-perfect').есть, false);
});

test('«Отличник» — пять домашек на девяносто и выше', () => {
  const домашки = (сколько, балл) => Object.fromEntries(
    Array.from({ length: сколько }, (_, i) => [`у${i}`, { homework: балл }]),
  );
  assert.equal(значок(итог(состояние(домашки(4, 30)), [КУРС], ДАТА), 'five-homework').есть, false);
  assert.equal(значок(итог(состояние(домашки(5, 30)), [КУРС], ДАТА), 'five-homework').есть, true);
  assert.equal(значок(итог(состояние(домашки(9, 20)), [КУРС], ДАТА), 'five-homework').есть, false,
    'сданная домашка без отличия не считается');
});

test('«Отличник» показывает, сколько уже набрано', () => {
  const итоги = итог(состояние({ у1: { homework: 30 }, у2: { homework: 30 } }), [КУРС], ДАТА);
  assert.equal(значок(итоги, 'five-homework').счёт, '2 из 5');
});

test('«Ударная неделя» — сто баллов за одну неделю, а не за всё время', () => {
  assert.equal(значок(итог(состояние({}, { '2026-W34': 99 }), [КУРС], ДАТА), 'week-100').есть, false);
  assert.equal(значок(итог(состояние({}, { '2026-W34': 100 }), [КУРС], ДАТА), 'week-100').есть, true);
  assert.equal(значок(итог(состояние({}, { '2026-W33': 60, '2026-W34': 60 }), [КУРС], ДАТА), 'week-100').есть, false,
    'две недели по шестьдесят — это не ударная неделя');
});

test('«Твёрдая рука» — три чистые игры, считая и определители', () => {
  const чистых = (сколько) => Object.fromEntries(
    Array.from({ length: сколько }, (_, i) => [`у${i}`, { game0: 15 }]),
  );
  assert.equal(значок(итог(состояние(чистых(2)), [КУРС], ДАТА), 'three-clean').есть, false);
  assert.equal(значок(итог(состояние(чистых(3)), [КУРС], ДАТА), 'three-clean').есть, true);

  const играИДваОпределителя = { у1: { game0: 15, key0: 15 }, у2: { key0: 15 } };
  assert.equal(значок(итог(состояние(играИДваОпределителя), [КУРС], ДАТА), 'three-clean').есть, true);
});

test('«Твёрдая рука» не засчитывает игру, пройденную с ошибкой', () => {
  const состояния = { у1: { game0: 15 }, у2: { game0: 10 }, у3: { game0: 15 } };
  const з = значок(итог(состояние(состояния), [КУРС], ДАТА), 'three-clean');
  assert.equal(з.есть, false);
  // Счёт виден и у неполученного значка: «2 из 3» говорит, что до него
  // осталась одна игра, а голое условие этого не говорит.
  assert.equal(з.счёт, '2 из 3');
});
