import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

import { собрать } from '../scripts/spisok-klassov.mjs';
import { строкаИтога } from '../js/pages/home.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/*
  Список классов лежит отдельным файлом, чтобы главная не запрашивала все пять
  курсов и не считала ответом 404 «класс ещё не написан»: от этого в консоли
  висели три ошибки, а карточки годов дёргались, когда ответы приходили.

  Плата за отдельный файл — возможность разойтись с файлами курсов. Стережёт
  её этот тест: он же и подсказывает, чем починить.
*/
test('список классов совпадает с файлами курсов', async () => {
  const ожидается = await собрать(ROOT);
  const лежит = JSON.parse(await readFile(join(ROOT, 'content', 'klassy.json'), 'utf8'));

  assert.deepEqual(
    лежит,
    ожидается,
    'content/klassy.json разошёлся с содержимым content/courses — пересобери: ' +
      'node scripts/spisok-klassov.mjs',
  );
});

test('класс без уроков в список не попадает', async () => {
  const { классы } = await собрать(ROOT);
  for (const к of классы) {
    assert.ok(к.уроков > 0, `${к.класс} класс попал в список с нулём уроков`);
    assert.ok(Number.isInteger(к.класс) && к.класс >= 5 && к.класс <= 9, `странный класс: ${к.класс}`);
  }
});

test('итог главной называет только написанные годы', () => {
  assert.equal(
    строкаИтога([{ класс: 5, уроков: 34 }, { класс: 7, уроков: 15 }], 5),
    'Сейчас на сайте 49 уроков: классы 5, 7. Остальные годы пишутся.',
  );
});

test('один написанный год — единственное число и без «остальных» во множественном', () => {
  assert.equal(
    строкаИтога([{ класс: 5, уроков: 1 }], 5),
    'Сейчас на сайте 1 урок — 5 класс. Остальные годы пишутся.',
  );
});

test('когда написано всё, оговорки про остальные годы нет', () => {
  const все = [5, 6, 7, 8, 9].map((класс) => ({ класс, уроков: 10 }));
  assert.equal(строкаИтога(все, 5), 'Сейчас на сайте 50 уроков: классы 5, 6, 7, 8, 9.');
});

test('без написанных уроков строки нет вовсе', () => {
  assert.equal(строкаИтога([], 5), '');
});
