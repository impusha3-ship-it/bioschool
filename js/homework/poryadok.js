/**
 * Порядок вариантов ответа и работы, сданные при старом порядке.
 *
 * Ответ на вопрос с выбором хранится в работе номером варианта. Стоит
 * переставить варианты в файле урока — и номер в уже сданной работе начнёт
 * указывать на другой вариант: разбор покажет ребёнку, что он выбрал то,
 * чего не выбирал.
 *
 * Поэтому каждая перестановка записывается в `content/perestanovki.json`
 * под своим номером, а каждая новая работа несёт номер порядка, при котором
 * сдана. Старая работа переводится на лету, при показе, — в базе ничего не
 * переписывается. Работа без номера сдана при самом первом порядке, первом.
 *
 * Первая перестановка — 17 сентября 2026: в 8 классе верным во всех
 * вопросах с одним ответом был первый вариант, а с несколькими — первые
 * подряд, и ответ угадывался без знания.
 */

/** Порядок, при котором сдаются работы сейчас. */
export const ТЕКУЩИЙ_ПОРЯДОК = 2;

/** Нужно ли переводить ответы этой работы. */
export function нуженПеревод(работа) {
  return Number(работа?.optionsVersion ?? 1) < ТЕКУЩИЙ_ПОРЯДОК;
}

/**
 * Ответы работы в текущем порядке вариантов.
 *
 * Перестановка `куда[i]` — новое место варианта, стоявшего на месте i.
 * Перестановки применяются по очереди, от следующей за порядком работы до
 * текущей: работа, сданная между двумя перемешиваниями, переводится только
 * через второе.
 */
export function перевестиОтветы(работа, lessonId, таблица = {}) {
  const ответы = { ...(работа?.answers ?? {}) };
  const с = Number(работа?.optionsVersion ?? 1);

  for (let версия = с + 1; версия <= ТЕКУЩИЙ_ПОРЯДОК; версия += 1) {
    const урок = таблица?.[версия]?.[lessonId];
    if (!урок) continue;
    for (const [id, куда] of Object.entries(урок)) {
      const был = ответы[id];
      if (Number.isInteger(был)) ответы[id] = куда[был] ?? был;
      else if (Array.isArray(был)) ответы[id] = был.map((i) => куда[i] ?? i);
    }
  }

  return ответы;
}
