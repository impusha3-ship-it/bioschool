import { el } from '../ui/dom.js';
import { loadCourse } from '../content.js';
import { итог } from '../progress/core.js';
import { progress } from '../progress/index.js';
import { auth } from './login.js';

/**
 * Личный прогресс: ступень, баллы, серия недель, значки и пройденное.
 *
 * Гостю показывается ровно то же самое: баллы считаются с первой секунды и без
 * входа. Разница одна — гостю сказано, что они живут только в этом браузере,
 * и это единственный честный повод войти. До геймификации такого повода не
 * было вовсе: гостю на сайте доступно всё, кроме сдачи работы.
 */
export async function renderMePage() {
  const состояние = progress.read();
  const курсы = await загрузитьКурсы(состояние);
  const свод = итог(состояние, курсы);
  const сессия = auth.current();

  const классБлок = el('div', { class: 'me__class' });
  if (сессия?.kind === 'student' && сессия.classId) наполнитьКласс(классБлок, сессия.classId);

  return el('section', { class: 'me' }, [
    el('h1', {}, 'Мой прогресс'),
    сессия?.kind === 'student' ? null : гостю(свод),
    ступеньБлок(свод),
    серияБлок(свод),
    урокиБлок(свод),
    значкиБлок(свод),
    классБлок,
  ]);
}

/**
 * Курсы тех классов, уроки которых уже встречались в прогрессе.
 * Класс берётся из начала идентификатора урока («5-griby» — пятый): держать
 * это отдельным полем значило бы дублировать то, что и так есть в имени.
 */
async function загрузитьКурсы(состояние) {
  const классы = new Set(
    Object.keys(состояние.lessons ?? {})
      .map((id) => id.split('-')[0])
      .filter((g) => /^[5-9]$/.test(g)),
  );

  const курсы = [];
  for (const grade of классы) {
    try {
      курсы.push(await loadCourse(grade));
    } catch {
      // Курс не открылся — обойдёмся без разбивки по разделам, всё остальное
      // на странице считается и без него.
    }
  }
  return курсы;
}

function гостю(свод) {
  return el('div', { class: 'me__guest' }, [
    el(
      'p',
      {},
      свод.xp
        ? `Твои ${свод.xp} баллов живут только в этом браузере.`
        : 'Баллы будут копиться прямо здесь, в браузере.',
    ),
    el('a', { class: 'button', href: '#/login' }, 'Войти и сохранить'),
  ]);
}

function ступеньБлок({ xp, ступень }) {
  const доля = ступень.следующая
    ? Math.round(((xp - ступень.порог) / (xp + ступень.доСледующей - ступень.порог)) * 100)
    : 100;

  return el('div', { class: 'me__level' }, [
    el('p', { class: 'me__level-name' }, ступень.имя),
    el('p', { class: 'me__xp' }, `${xp} ${баллов(xp)}`),
    полоса(доля),
    el(
      'p',
      { class: 'me__next' },
      ступень.следующая
        ? `До ступени «${ступень.следующая}» ещё ${ступень.доСледующей}`
        : 'Это последняя ступень',
    ),
  ]);
}

function серияБлок({ серия }) {
  return el('div', { class: 'me__streak' }, [
    el(
      'p',
      {},
      серия
        ? `Занимаешься ${серия} ${недель(серия)} подряд`
        : 'Серия начнётся с первого балла на этой неделе',
    ),
  ]);
}

function урокиБлок({ уроки }) {
  if (!уроки.всего) return null;

  return el('div', { class: 'me__lessons' }, [
    el('h2', {}, 'Пройдено'),
    el('p', { class: 'me__lessons-count' }, `${уроки.пройдено} из ${уроки.всего}`),
    полоса(Math.round((уроки.пройдено / уроки.всего) * 100)),
    el(
      'ul',
      { class: 'me__sections' },
      уроки.разделы.map((р) =>
        el('li', {}, [
          el('span', { class: 'me__section-title' }, р.title),
          el('span', { class: 'me__section-count' }, `${р.пройдено} из ${р.всего}`),
        ]),
      ),
    ),
  ]);
}

/**
 * Значки. Неполученные показываются тоже, и с условием: значок, о котором
 * не знаешь, ни к чему не зовёт, а список из одних полученных не говорит,
 * куда идти дальше.
 */
function значкиБлок({ значки }) {
  return el('div', { class: 'me__awards' }, [
    el('h2', {}, 'Значки'),
    el(
      'ul',
      { class: 'me__awards-list' },
      значки.map((з) =>
        el('li', { class: з.есть ? 'award award--has' : 'award' }, [
          el('span', { class: 'award__name' }, з.имя),
          el('span', { class: 'award__hint' }, з.есть ? (з.счёт ?? 'получен') : з.условие),
        ]),
      ),
    ),
  ]);
}

/**
 * Шкала класса и герои недели. Наполняется отдельно от остальной страницы:
 * личная часть уже посчитана из браузера, и заставлять её ждать сеть незачем.
 */
async function наполнитьКласс(узел, classId) {
  let шкала;
  try {
    шкала = await progress.шкалаКласса(classId);
  } catch {
    return; // Не открылось — личная часть на экране, и этого довольно.
  }
  if (!шкала) return;

  узел.append(
    el('h2', {}, 'Класс'),
    el(
      'p',
      { class: 'me__class-count' },
      шкала.цель
        ? `Класс прошёл ${шкала.пройдено} из ${шкала.цель}`
        : `Класс прошёл уроков: ${шкала.пройдено}`,
    ),
    полоса(шкала.цель ? Math.round((шкала.пройдено / шкала.цель) * 100) : 0),
  );

  if (шкала.герои.length) {
    узел.append(
      el('h3', {}, 'Герои недели'),
      el(
        'ol',
        { class: 'me__heroes' },
        шкала.герои.map((г) => el('li', {}, `${г.имя} — ${г.xp}`)),
      ),
    );
  }
}

function полоса(процент) {
  const доля = Math.max(0, Math.min(100, процент));
  const заполнение = el('div', { class: 'bar__fill' });
  заполнение.setAttribute('style', `width: ${доля}%`);

  return el(
    'div',
    {
      class: 'bar',
      role: 'progressbar',
      'aria-valuenow': String(доля),
      'aria-valuemin': '0',
      'aria-valuemax': '100',
    },
    [заполнение],
  );
}

/** Склонения: «1 неделю подряд» читается, «1 недель подряд» — нет. */
function недель(n) {
  const остаток = n % 10;
  if (n % 100 >= 11 && n % 100 <= 14) return 'недель';
  if (остаток === 1) return 'неделю';
  if (остаток >= 2 && остаток <= 4) return 'недели';
  return 'недель';
}

function баллов(n) {
  const остаток = n % 10;
  if (n % 100 >= 11 && n % 100 <= 14) return 'баллов';
  if (остаток === 1) return 'балл';
  if (остаток >= 2 && остаток <= 4) return 'балла';
  return 'баллов';
}
