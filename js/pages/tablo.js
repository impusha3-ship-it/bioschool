import { el } from '../ui/dom.js';
import { полоса } from '../ui/bar.js';
import * as rest from '../api/firebase-rest.js';
import { SCHOOL_ID } from '../firebase-config.js';
import { неделя as неделяИз } from '../progress/weeks.js';
import { БОНУС_ЗА_100, сданоКлассом, успешность } from '../homework/pochyot.js';

const ROOT = `schools/${SCHOOL_ID}`;

/*
  Тройка, а не пятёрка. Таблица почёта — это место, куда попадают, и чем
  короче список, тем он дороже: пятое место из пятерых не значит ничего.
  Столько же берётся и по классу, чтобы «третий в школе» и «третий в классе»
  весили одинаково.
*/
const ЛУЧШИХ_ПО_ШКОЛЕ = 3;
const ЛУЧШИХ_ПО_КЛАССУ = 3;

/**
 * Собирает таблицу почёта: лучшие по всей школе и по каждому классу.
 *
 * Считается **только по сданным домашним работам** — решение учителя от
 * 16 сентября 2026. Тренажёр открыт всем и всегда, домашку задаёт учитель
 * классу и сдаётся она один раз; сложи всё вместе, и впереди окажется тот,
 * у кого больше свободного времени, а не тот, кто лучше учится. Баллы за
 * игры и тренажёр никуда не делись — они считаются в «Моём прогрессе», в
 * ступени и в значках, просто места в почёте не дают.
 *
 * Чистая функция — данные приходят готовыми. Списки строятся от `students`,
 * а не от самой таблицы баллов: таблица открыта на чтение и на запись
 * каждому за свою строку, и брать из неё список учеников значило бы верить
 * тому, что туда написали. Правила чужую строку не пустят, но проверка по
 * списку дешевле доверия.
 */
export function собратьТабло({ classes = {}, students = {}, leaderboard = {}, assignments = {}, неделя } = {}) {
  const задано = (classId) => Object.keys(assignments?.[classId] ?? {}).length;
  const заданоЗаНеделю = (classId) => Object.values(assignments?.[classId] ?? {})
    .filter((a) => Number.isFinite(a?.assignedAt) && неделяИз(new Date(a.assignedAt)) === неделя).length;

  const строки = Object.entries(students).map(([id, ученик]) => {
    const запись = leaderboard?.[ученик.classId]?.[id] ?? {};
    return {
      id,
      имя: ученик.name,
      classId: ученик.classId,
      класс: classes[ученик.classId]?.title ?? '',
      // В строке ученика два счёта: `xp` — всё, что он набрал (по нему
      // учитель видит ступень), `hwXp` — только домашние работы. Почёт
      // строится по второму.
      xp: число(запись.hwXp),
      weekXp: запись.weekId === неделя ? число(запись.hwWeekXp) : 0,
      hwDone: число(запись.hwDone),
      hwWeekDone: запись.weekId === неделя ? число(запись.hwWeekDone) : 0,
      задано: задано(ученик.classId),
      заданоЗаНеделю: заданоЗаНеделю(ученик.classId),
    };
  });

  /*
    Школьный почёт — по успешности, а не по сумме: классам задают разное
    число работ, и по сумме впереди оказывался тот класс, которому задали
    больше. Процент считается из заданного, а не из сданного (решение
    учителя от 17 сентября 2026): несданная работа — ноль. Иначе три
    безупречные работы из пяти заданных давали бы 100% и первое место.

    За неделю — из заданного на этой неделе, но не меньше сданного за неделю:
    доделанная старая работа не должна поднимать процент выше ста.

    При равном проценте выше тот, кто сдал больше, потом по алфавиту —
    чтобы порядок не прыгал между заходами.
  */
  const поУспешности = (сп, баллы, из, сдано) => сп
    .map((с) => ({ ...с, процент: успешность(баллы(с), из(с)) }))
    .filter((с) => с.процент !== null && с.процент > 0)
    .sort((a, b) => b.процент - a.процент || сдано(b) - сдано(a) || a.имя.localeCompare(b.имя, 'ru'));

  const школаВсегда = поУспешности(
    строки, (с) => с.xp, (с) => Math.max(с.задано, с.hwDone), (с) => с.hwDone,
  );
  const школаНеделя = поУспешности(
    строки, (с) => с.weekXp, (с) => Math.max(с.заданоЗаНеделю, с.hwWeekDone), (с) => с.hwWeekDone,
  );

  const поВсегда = (сп) => сп.filter((с) => с.xp > 0).sort((a, b) => b.xp - a.xp);
  const поНеделе = (сп) => сп.filter((с) => с.weekXp > 0).sort((a, b) => b.weekXp - a.weekXp);

  return {
    школа: {
      всегда: школаВсегда.slice(0, ЛУЧШИХ_ПО_ШКОЛЕ),
      неделя: школаНеделя.slice(0, ЛУЧШИХ_ПО_ШКОЛЕ),
    },
    классы: Object.entries(classes).map(([id, класс]) => {
      const свои = строки.filter((с) => с.classId === id);
      // Шкала класса — сданные домашние работы из заданных.
      const { сдано, задано, процент } = сданоКлассом(свои, assignments?.[id]);
      return {
        id,
        title: класс.title,
        учеников: свои.length,
        сдано,
        задано,
        процент,
        неделя: поНеделе(свои).slice(0, ЛУЧШИХ_ПО_КЛАССУ),
        всегда: поВсегда(свои).slice(0, ЛУЧШИХ_ПО_КЛАССУ),
      };
    }),
  };
}

function число(v) {
  return typeof v === 'number' && Number.isFinite(v) ? v : 0;
}

/**
 * Таблица почёта. Показывается и с проектора в начале урока, и с телефона:
 * входа она не требует — таблица баллов и списки классов открыты на чтение.
 *
 * Раньше сюда вела только прямая ссылка, которую знал учитель. Теперь на
 * страницу ходят и ученики с главной, поэтому сверху стоит дорога назад:
 * без неё зашедший с телефона упирается в тупик и жмёт «назад» в браузере.
 */
export async function renderTabloPage() {
  const блок = el('section', { class: 'tablo' }, [
    шапка(),
    el('p', { class: 'loading' }, 'Загружаю…'),
  ]);

  наполнить(блок);
  return блок;
}

async function наполнить(блок) {
  let данные;
  try {
    const [classes, students, leaderboard, assignments] = await Promise.all([
      rest.dbGet(`${ROOT}/classes`),
      rest.dbGet(`${ROOT}/students`),
      rest.dbGet(`${ROOT}/leaderboard`),
      rest.dbGet(`${ROOT}/assignments`),
    ]);
    данные = собратьТабло({
      classes: classes ?? {},
      students: students ?? {},
      leaderboard: leaderboard ?? {},
      assignments: assignments ?? {},
      неделя: неделяИз(new Date()),
    });
  } catch (error) {
    блок.replaceChildren(
      шапка(),
      el('p', { class: 'login__error' }, `Не открылось: ${error.message}`),
    );
    return;
  }

  блок.replaceChildren(
    шапка(),
    столбцыШколы(данные.школа),
    ...данные.классы.map(карточкаКласса),
  );
}

/*
  Под заголовком сказано, что считается. Без этой строчки ученик, у которого
  в шапке сайта висит «Прогресс · 120», а в почёте стоит 30, решит, что его
  обсчитали, — и будет прав в том, что объяснить это ему никто не потрудился.
*/
function шапка() {
  return el('div', { class: 'tablo__top' }, [
    el('a', { class: 'back-link', href: '#/' }, '← На главную'),
    el('h1', { class: 'tablo__title' }, 'Таблица почёта'),
    el('p', { class: 'tablo__lead' },
      'Считаются только сданные домашние работы: чем правильнее работа, тем больше баллов, ' +
      'и учитывается оценка учителя за развёрнутый ответ. За работу без единой ошибки — ' +
      `ещё ${БОНУС_ЗА_100} бонусных. Игры и тренажёр сюда не идут — они копятся в «Моём прогрессе».`),
    el('p', { class: 'tablo__lead' },
      'Классам задают разное число работ, поэтому в школьных списках место решает не сумма, а процент: ' +
      'сколько набрано из всех работ, заданных твоему классу. Несданная работа считается нулём. ' +
      'Внутри класса всем задано одно и то же — там считается сумма баллов.'),
  ]);
}

function столбцыШколы(школа) {
  return el('div', { class: 'tablo__school' }, [
    список('Тройка школы за всё время', школа.всегда, (с) => `${с.процент}%`,
      'Пока никто не сдал и половины заданных работ'),
    список('Герои недели', школа.неделя, (с) => `${с.процент}%`, 'На этой неделе работ пока никто не сдал'),
  ]);
}

function список(заголовок, строки, значение, пусто) {
  return el('div', { class: 'tablo__block' }, [
    el('h2', { class: 'tablo__head' }, заголовок),
    строки.length
      ? el('ol', { class: 'tablo__list' }, строки.map((с, i) => строкаТабло(с, i, значение(с))))
      : el('p', { class: 'tablo__empty' }, пусто),
  ]);
}

function строкаТабло(с, место, баллы) {
  return el('li', { class: 'tablo__row' }, [
    el('span', { class: 'tablo__place' }, String(место + 1)),
    el('span', { class: 'tablo__name' }, с.имя),
    с.класс ? el('span', { class: 'tablo__class' }, с.класс) : null,
    el('span', { class: 'tablo__xp' }, String(баллы)),
  ]);
}

/**
 * Карточка класса: тройка за всё время и тройка этой недели.
 *
 * Два списка, а не один, потому что они зовут к разному. За всё время —
 * это почёт, и он почти не меняется: тот, кто набрал больше всех к марту,
 * останется первым и в апреле. Неделя же обнуляется каждый понедельник, и
 * попасть в неё может любой — в том числе тот, кому до общей тройки ещё
 * далеко. Без недели таблица почёта была бы списком одних и тех же фамилий.
 */
function карточкаКласса(класс) {
  return el('div', { class: 'tablo__class-card' }, [
    el('h2', { class: 'tablo__head' }, класс.title),
    el('p', { class: 'tablo__count' },
      класс.задано
        ? `Сдано домашних работ: ${класс.сдано} из ${класс.задано}`
        : 'Домашних работ классу пока не задано'),
    класс.задано ? полоса(класс.процент) : null,
    el('div', { class: 'tablo__class-lists' }, [
      списокКласса('Лучшие за всё время', класс.всегда, (с) => с.xp, 'Баллов в классе пока нет'),
      списокКласса('На этой неделе', класс.неделя, (с) => с.weekXp, 'На этой неделе баллов ещё нет'),
    ]),
  ]);
}

/** Тройка внутри класса. Класс в строке не пишется — он написан над списком. */
function списокКласса(заголовок, строки, значение, пусто) {
  return el('div', { class: 'tablo__class-block' }, [
    el('h3', { class: 'tablo__sub' }, заголовок),
    строки.length
      ? el('ol', { class: 'tablo__list tablo__list--small' },
          строки.map((с, i) => строкаТабло({ ...с, класс: '' }, i, значение(с))))
      : el('p', { class: 'tablo__empty' }, пусто),
  ]);
}
