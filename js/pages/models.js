import { el } from '../ui/dom.js';
import { ГРУППЫ, ОРГАНОИДЫ, создатьСцену } from '../models/kletka.js';

/**
 * Раздел «Модели»: трёхмерная клетка, которую можно повернуть и разобрать.
 *
 * Плоская схема в конспекте показывает, где что лежит, но не показывает, что
 * клетка — объём: ученик запоминает картинку, а не устройство. Здесь клетку
 * можно повернуть, заглянуть в вырезанную четверть и ткнуть в органоид.
 *
 * Библиотека и сама сцена загружаются только на этой странице. Остальные
 * страницы сайта весят столько же, сколько весили: шестьсот килобайт
 * `three.js` не должны ехать к тому, кто открыл конспект.
 */

/** Порядок важен: OrbitControls дописывается в уже загруженный THREE. */
const БИБЛИОТЕКИ = ['./js/vendor/three.min.js', './js/vendor/OrbitControls.js'];

/*
  Загруженные скрипты помнятся: между переходами по сайту страница создаётся
  заново, а библиотеку второй раз грузить незачем.
*/
const загруженные = new Map();

function загрузитьСкрипт(src) {
  if (загруженные.has(src)) return загруженные.get(src);

  const ожидание = new Promise((готово, ошибка) => {
    const узел = document.createElement('script');
    узел.src = src;
    узел.addEventListener('load', () => готово(), { once: true });
    узел.addEventListener('error', () => ошибка(new Error(`не загрузилось: ${src}`)), { once: true });
    document.head.append(узел);
  });

  // Неудачу не помним: на следующем открытии страницы попробуем снова —
  // сеть могла отвалиться на секунду.
  ожидание.catch(() => загруженные.delete(src));
  загруженные.set(src, ожидание);
  return ожидание;
}

async function загрузитьТри() {
  for (const src of БИБЛИОТЕКИ) await загрузитьСкрипт(src);
  if (!globalThis.THREE?.WebGLRenderer || !globalThis.THREE?.OrbitControls) {
    throw new Error('библиотека загрузилась не полностью');
  }
  return globalThis.THREE;
}

/** Ученик просил не двигать лишнего — это уважается и сценой, и подсказками. */
function сниженнаяАнимация() {
  return Boolean(globalThis.matchMedia?.('(prefers-reduced-motion: reduce)').matches);
}

/**
 * Что показать, если трёхмерного не вышло: старый компьютер без WebGL,
 * закрытый школьной сетью файл, отключённые скрипты у одного из детей.
 * Пустая рамка в этом месте — худшее, что можно сделать: ученик решит, что
 * сломался он.
 */
function заглушка(причина) {
  return el('div', { class: 'models__fallback' }, [
    el('p', {}, 'Трёхмерная модель на этом устройстве не открылась.'),
    el('p', { class: 'models__fallback-why' }, причина),
    el('img', {
      class: 'models__fallback-img',
      src: './img/bio/zhivotnaya-kletka-bez-podpisey.svg',
      alt: 'Плоская схема животной клетки: оболочка, крупное ядро с ядрышком, овальная '
        + 'митохондрия, мелкие пузырьки и пара палочек клеточного центра.',
    }),
    el('p', {}, [
      'Строение клетки с подписями разобрано в уроке ',
      el('a', { href: '#/lesson/8-zhivotnaya-kletka' }, '«Животная клетка»'),
      '.',
    ]),
  ]);
}

/** Карточка органоида: то же, что учитель диктует под запись. */
function карточка(ключ) {
  if (!ключ) {
    return el('div', { class: 'models__card models__card--empty' }, [
      el('p', {}, 'Выбери органоид в списке или ткни в него на модели — здесь появится, из чего он и на что он.'),
    ]);
  }

  const о = ОРГАНОИДЫ[ключ];
  return el('div', { class: 'models__card' }, [
    el('h2', {}, о.name),
    el('p', { class: 'models__card-type' }, о.size ? `${о.type} · ${о.size}` : о.type),
    el('h3', {}, 'Строение'),
    el('p', {}, о.structure),
    el('h3', {}, 'Работа в клетке'),
    el('ul', {}, о.functions.map((ф) => el('li', {}, ф))),
  ]);
}

export async function renderModelsPage() {
  const обёртка = el('section', { class: 'models' }, [
    el('h1', {}, 'Животная клетка в объёме'),
    el('p', { class: 'models__lead' },
      'Клетку можно повернуть, приблизить и разобрать по частям. Четверть вырезана, '
      + 'чтобы было видно внутрь. Размеры схематичны: уместить в один кадр ядро и рибосому '
      + 'в настоящем масштабе нельзя — ядро крупнее рибосомы в сотни раз.'),
  ]);

  let THREE;
  try {
    THREE = await загрузитьТри();
  } catch (ошибка) {
    обёртка.append(заглушка(`Не удалось загрузить трёхмерную библиотеку: ${ошибка.message}.`));
    return обёртка;
  }

  const canvas = el('canvas', { class: 'models__canvas' });
  const подписи = el('div', { class: 'models__labels', 'aria-hidden': 'true' });
  const сцена = el('div', { class: 'models__stage' }, [canvas, подписи]);

  let модель;
  try {
    модель = создатьСцену({ THREE, canvas, сниженнаяАнимация: сниженнаяАнимация() });
  } catch (ошибка) {
    обёртка.append(заглушка(
      'Похоже, браузер не умеет показывать трёхмерную графику (WebGL). '
      + `Сообщение браузера: ${ошибка.message}.`,
    ));
    return обёртка;
  }

  /*
    Полотно — картинка, и для чтения с экрана оно бесполезно: повернуть его
    голосом нельзя. Поэтому у него короткое описание, а вся суть — в списке
    органоидов рядом, который сделан обычными кнопками.
  */
  canvas.setAttribute('role', 'img');
  canvas.setAttribute('aria-label',
    'Трёхмерная модель животной клетки с вырезанной четвертью. Всё, что на ней показано, '
    + 'перечислено в списке органоидов ниже.');

  // ---------- кнопки ----------
  const кнопка = (текст, подсказка) => el('button', {
    class: 'models__tool', type: 'button', 'aria-pressed': 'false', title: подсказка,
  }, текст);

  const кРазрез = кнопка('Разрез', 'Показать клетку целиком или с вырезанной четвертью');
  const кПодписи = кнопка('Подписи', 'Названия органоидов прямо на модели');
  const кВращение = кнопка('Вращение', 'Медленный поворот сам собой');
  const кСброс = el('button', { class: 'models__tool', type: 'button' }, 'Вид сначала');

  let подписиВидны = true;
  const отметить = (кнопка_, включено) => кнопка_.setAttribute('aria-pressed', String(включено));
  отметить(кРазрез, модель.разрезВключён());
  отметить(кПодписи, подписиВидны);
  отметить(кВращение, модель.автоповоротВключён());

  кРазрез.addEventListener('click', () => отметить(кРазрез, модель.переключитьРазрез()));
  кВращение.addEventListener('click', () => отметить(кВращение, модель.переключитьАвтоповорот()));
  кСброс.addEventListener('click', () => модель.сброс());
  кПодписи.addEventListener('click', () => {
    подписиВидны = !подписиВидны;
    отметить(кПодписи, подписиВидны);
    расставить();
  });

  const инструменты = el('div', { class: 'models__tools' }, [кРазрез, кПодписи, кВращение, кСброс]);

  // ---------- список органоидов ----------
  const кнопкиСписка = new Map();
  const список = el('div', { class: 'models__list' }, ГРУППЫ.map(([название, ключи]) => el('div', { class: 'models__group' }, [
    el('h2', { class: 'models__group-title' }, название),
    el('ul', {}, ключи.map((ключ) => {
      const б = el('button', { class: 'models__pick', type: 'button', 'aria-pressed': 'false' }, [
        el('span', { class: 'models__dot', style: `--dot:${ОРГАНОИДЫ[ключ].color}` }),
        ОРГАНОИДЫ[ключ].short,
      ]);
      б.addEventListener('click', () => выбрать(модель.выбранный() === ключ ? null : ключ));
      кнопкиСписка.set(ключ, б);
      return el('li', {}, б);
    })),
  ])));

  const место = el('div', { class: 'models__card-slot' }, карточка(null));

  /** Выбор — одно место: и щелчок по модели, и кнопка списка идут сюда. */
  function выбрать(ключ) {
    модель.выбрать(ключ);
    for (const [k, б] of кнопкиСписка) б.setAttribute('aria-pressed', String(k === ключ));
    место.replaceChildren(карточка(ключ));
    расставить();
  }

  // ---------- щелчок по модели ----------
  /*
    Различаем щелчок и поворот: OrbitControls вращает клетку тем же нажатием,
    и если считать выбором любое отпускание кнопки, то после каждого поворота
    выделялся бы случайный органоид. Считается смещение и время.
  */
  let нажато = null;
  canvas.addEventListener('pointerdown', (e) => {
    нажато = { x: e.clientX, y: e.clientY, t: performance.now() };
  });
  canvas.addEventListener('pointerup', (e) => {
    if (!нажато) return;
    const уехало = Math.hypot(e.clientX - нажато.x, e.clientY - нажато.y);
    const долго = performance.now() - нажато.t > 600;
    нажато = null;
    if (уехало > 6 || долго) return;

    const ключ = модель.подКурсором(e.clientX, e.clientY);
    выбрать(ключ && ключ === модель.выбранный() ? null : ключ);
  });
  canvas.addEventListener('pointercancel', () => { нажато = null; });

  /*
    Первое касание модели останавливает сам поворот: ученик взялся смотреть
    сам, и вырывать клетку из рук не надо. Кнопкой вращение включается обратно.
  */
  canvas.addEventListener('pointerdown', () => {
    if (модель.остановитьАвтоповорот()) отметить(кВращение, false);
  }, { once: true });

  // ---------- подписи над моделью ----------
  const ярлыки = new Map();
  for (const ключ of Object.keys(ОРГАНОИДЫ)) {
    const я = el('button', {
      class: 'models__label', type: 'button', tabindex: '-1',
      style: `--dot:${ОРГАНОИДЫ[ключ].color}`,
    }, ОРГАНОИДЫ[ключ].short);
    я.addEventListener('click', () => выбрать(модель.выбранный() === ключ ? null : ключ));
    подписи.append(я);
    ярлыки.set(ключ, я);
  }

  let ширина = 0;
  let высота = 0;

  /*
    Размеры подписей мерятся один раз и запоминаются: по ним считается, кто
    кому мешает, а спрашивать `offsetWidth` у двенадцати кнопок в каждом кадре
    значит заставлять браузер пересчитывать вёрстку шестьдесят раз в секунду.
    Текст подписей не меняется, так что мерить заново незачем.
  */
  const размеры = new Map();
  function замерить() {
    for (const [ключ, я] of ярлыки) {
      const было = я.hidden;
      я.hidden = false;
      if (я.offsetWidth) размеры.set(ключ, { w: я.offsetWidth, h: я.offsetHeight });
      я.hidden = было;
    }
  }

  /**
   * Расставляет подписи по экранным точкам органоидов.
   *
   * Когда органоид выбран, остальные подписи убираются: двенадцать названий
   * поверх полупрозрачной клетки читаются хуже, чем одно нужное.
   *
   * Пока выбора нет, подписи спорят за место — при повороте они то и дело
   * сходятся в одну точку, и в исходном виде «Мембрана» с «Лизосомами»
   * налезали друг на друга. Спор решается глубиной: ближняя к зрителю
   * остаётся, накрытая ею прячется. Двигать подпись в свободное место нельзя
   * — она перестанет указывать на свой органоид.
   */
  function расставить() {
    const выбран = модель.выбранный();
    const точки = [];

    for (const [ключ, я] of ярлыки) {
      const нужна = подписиВидны && (!выбран || выбран === ключ);
      const точка = нужна && ширина ? модель.местоПодписи(ключ, ширина, высота) : null;
      я.classList.toggle('models__label--on', выбран === ключ);
      if (точка) точки.push({ ключ, я, ...точка });
      else я.hidden = true;
    }

    точки.sort((a, b) => a.z - b.z);
    const занято = [];

    for (const т of точки) {
      // Просвет между подписями заметно больше нуля: две подписи, разошедшиеся
      // на пиксель, читаются как одна слипшаяся.
      const р = размеры.get(т.ключ) ?? { w: 96, h: 22 };
      const рамка = {
        x1: т.x - р.w / 2 - 7, x2: т.x + р.w / 2 + 7,
        y1: т.y - р.h / 2 - 5, y2: т.y + р.h / 2 + 5,
      };
      const мешает = занято.some((д) => рамка.x1 < д.x2 && рамка.x2 > д.x1 && рамка.y1 < д.y2 && рамка.y2 > д.y1);
      if (мешает) {
        т.я.hidden = true;
        continue;
      }
      занято.push(рамка);
      т.я.hidden = false;
      т.я.style.left = `${Math.round(т.x)}px`;
      т.я.style.top = `${Math.round(т.y)}px`;
    }
  }

  /**
   * Подгоняет полотно под место, которое ему отвела вёрстка.
   *
   * Мерится место, а не берётся из `ResizeObserver`: первый размер иначе
   * зависел бы от того, доставит ли наблюдатель запись, — а он не доставит
   * ни в браузере, где его нет, ни во вкладке, которую открыли в фоне. Там
   * полотно осталось бы стартовым, 300 на 150, и клетка вышла бы размытым
   * пятном на всю рамку.
   */
  function подогнатьПоМесту() {
    const r = сцена.getBoundingClientRect();
    if (!r.width || !r.height) return false;
    if (Math.abs(r.width - ширина) < 0.5 && Math.abs(r.height - высота) < 0.5) return false;
    ширина = r.width;
    высота = r.height;
    модель.подогнать(ширина, высота);
    return true;
  }

  const наблюдатель = typeof ResizeObserver === 'function'
    ? new ResizeObserver(() => { подогнатьПоМесту(); расставить(); })
    : null;
  наблюдатель?.observe(сцена);

  /*
    Собственный кадровый цикл — только для подписей: они висят в разметке, а
    не в сцене, и сами за поворотом не поедут. Здесь же сторож: страница
    сайта сменяется заменой содержимого, без всякого «страница закрылась», и
    если сцену не остановить, брошенная клетка будет крутиться в памяти,
    считая кадры, до перезагрузки вкладки.
  */
  let ставилась = false;
  let кадр = requestAnimationFrame(function шаг() {
    if (сцена.isConnected) {
      // Мерить подписи можно только когда страница уже в документе: до этого
      // у скрытых кнопок нет никакой ширины.
      if (!ставилась) замерить();
      ставилась = true;
    } else if (ставилась) {
      наблюдатель?.disconnect();
      модель.остановить();
      return;
    }
    подогнатьПоМесту();
    расставить();
    кадр = requestAnimationFrame(шаг);
  });
  globalThis.addEventListener('pagehide', () => {
    cancelAnimationFrame(кадр);
    модель.остановить();
  }, { once: true });

  обёртка.append(
    сцена,
    инструменты,
    el('p', { class: 'models__hint' },
      'Потяни модель, чтобы повернуть; взял — работает и колесо, оно приближает. '
      + 'Щелчок по органоиду выбирает его, повторный — снимает выбор.'),
    el('div', { class: 'models__body' }, [список, место]),
  );
  return обёртка;
}
