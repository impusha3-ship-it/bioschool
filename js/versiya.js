/**
 * Слежение за версией сайта.
 *
 * Сайт — одна страница: переходы между разделами идут без перезагрузки, и
 * код, загруженный при открытии вкладки, работает, пока вкладку не закроют.
 * 17 сентября 2026 это вылезло на глазах у учителя: после выкладки нового
 * почёта у неё в открытой вкладке всё ещё стоял старый, а у детей, державших
 * сайт открытым с утра, — старые подсказки и старый порядок вариантов.
 *
 * Поэтому вкладка запоминает версию, с которой открылась, и время от времени
 * сверяется с `version.json`. Если вышла новая, страница перезагружается на
 * ближайшем переходе между разделами — не посреди работы: переход ученик
 * делает сам, и то, что он вписывал, в этот момент уже не на экране.
 *
 * Сама версия — отпечаток файлов сайта, его пересчитывает
 * `scripts/versiya.mjs`, а тест не даст выложить сайт со старым отпечатком.
 */

const АДРЕС = './version.json';

/** Чаще раза в пять минут не спрашиваем: сеть у детей бывает медленной. */
export const ПАУЗА_МС = 5 * 60 * 1000;

/**
 * Перезагрузка не чаще раза в две минуты. Страховка от петли: если что-то
 * пошло не так и после перезагрузки версия всё равно кажется новой, вкладка
 * не будет перезагружаться на каждом переходе.
 */
export const ПАУЗА_ПЕРЕЗАГРУЗКИ_МС = 2 * 60 * 1000;
const КЛЮЧ_ПЕРЕЗАГРУЗКИ = 'bioschool.versiya.reload';

export function createВерсия({
  fetchFn = globalThis.fetch,
  now = () => Date.now(),
  хранилище = globalThis.sessionStorage,
} = {}) {
  let своя = null;
  let свежая = null;
  let проверено = 0;
  let идёт = null;

  async function прочитать() {
    const ответ = await fetchFn(`${АДРЕС}?t=${now()}`, { cache: 'no-store' });
    if (!ответ.ok) return null;
    const данные = await ответ.json();
    return typeof данные?.версия === 'string' ? данные.версия : null;
  }

  /** Запоминает версию, с которой открылась вкладка. */
  async function запомнить() {
    try {
      своя = await прочитать();
      свежая = своя;
      проверено = now();
    } catch {
      // Не узнали — сверять не с чем, и вкладка просто работает как раньше.
    }
    return своя;
  }

  /**
   * Сверяется с сайтом, но не чаще паузы. Ничего не перезагружает — только
   * запоминает, что пора. Сбой сети молча пропускается: это не повод мешать.
   */
  function проверить({ сразу = false } = {}) {
    if (!своя) return Promise.resolve(false);
    if (идёт) return идёт;
    if (!сразу && now() - проверено < ПАУЗА_МС) return Promise.resolve(устарела());
    проверено = now();
    идёт = прочитать()
      .then((версия) => { if (версия) свежая = версия; })
      .catch(() => {})
      .then(() => { идёт = null; return устарела(); });
    return идёт;
  }

  /** Вышла ли новая версия, пока вкладка была открыта. */
  function устарела() {
    return Boolean(своя && свежая && свежая !== своя);
  }

  /** Можно ли перезагрузиться сейчас — не было ли перезагрузки только что. */
  function можноПерезагрузить() {
    try {
      const было = Number(хранилище?.getItem(КЛЮЧ_ПЕРЕЗАГРУЗКИ)) || 0;
      return now() - было >= ПАУЗА_ПЕРЕЗАГРУЗКИ_МС;
    } catch {
      return true;
    }
  }

  function отметитьПерезагрузку() {
    try {
      хранилище?.setItem(КЛЮЧ_ПЕРЕЗАГРУЗКИ, String(now()));
    } catch {
      // Хранилище закрыто — страховка от петли не сработает, но и петли не
      // будет: после перезагрузки версия запомнится заново.
    }
  }

  return { запомнить, проверить, устарела, можноПерезагрузить, отметитьПерезагрузку };
}

/**
 * Перезагрузка со свежим кодом.
 *
 * Обычная перезагрузка берёт файлы из кеша браузера — GitHub Pages разрешает
 * хранить их десять минут, — и вкладка открылась бы снова со старым кодом.
 * Поэтому сначала все уже загруженные файлы сайта запрашиваются заново мимо
 * кеша: это обновляет сам кеш. Новые файлы, которых раньше не было, в кеше и
 * так отсутствуют.
 */
export async function перезагрузитьСвежим({
  win = globalThis.window,
  fetchFn = globalThis.fetch,
  ждатьМс = 4000,
} = {}) {
  const свои = new Set();
  for (const запись of win.performance?.getEntriesByType?.('resource') ?? []) {
    try {
      const адрес = new URL(запись.name);
      if (адрес.origin !== win.location.origin) continue;
      if (!/\.(js|css|json|svg)$/.test(адрес.pathname)) continue;
      свои.add(адрес.origin + адрес.pathname);
    } catch {
      // Непонятная запись — пропускаем.
    }
  }

  const обновить = Promise.all(
    [...свои].map((адрес) => fetchFn(адрес, { cache: 'reload' }).catch(() => null)),
  );
  // Долго не ждём: медленная сеть не должна держать ученика на переходе.
  await Promise.race([обновить, new Promise((готово) => setTimeout(готово, ждатьМс))]);
  win.location.reload();
}
