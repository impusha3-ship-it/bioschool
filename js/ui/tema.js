/**
 * Выбор темы руками.
 *
 * По умолчанию тема берётся из системы — так и было раньше. Но школьный
 * ноутбук почти всегда стоит на светлой теме, а читать конспект вечером
 * удобнее на тёмной, и наоборот: в кабинете при солнце тёмная слепит.
 * Поэтому появился третий вариант — «как в системе», и переключатель ходит
 * по кругу между тремя.
 *
 * Выбор помнится в браузере. Если память недоступна (приватное окно,
 * запрет на данные сайтов), переключатель всё равно работает — просто
 * забывается при следующем заходе.
 */

export const ТЕМЫ = ['система', 'день', 'ночь'];

const КЛЮЧ = 'bio-tema';

const ПОДПИСИ = {
  система: 'Авто',
  день: 'День',
  ночь: 'Ночь',
};

const ПОЯСНЕНИЯ = {
  система: 'Тема: как в системе. Нажми, чтобы включить светлую',
  день: 'Тема: светлая. Нажми, чтобы включить тёмную',
  ночь: 'Тема: тёмная. Нажми, чтобы вернуть системную',
};

/** Следующая тема по кругу. Незнакомое значение считается системным. */
export function следующая(тема) {
  const i = ТЕМЫ.indexOf(тема);
  return ТЕМЫ[(i + 1) % ТЕМЫ.length] ?? ТЕМЫ[1];
}

/** Короткая подпись на кнопке. */
export function подпись(тема) {
  return ПОДПИСИ[тема] ?? ПОДПИСИ.система;
}

/** Полное пояснение — для тех, кто слушает страницу, а не смотрит. */
export function пояснение(тема) {
  return ПОЯСНЕНИЯ[тема] ?? ПОЯСНЕНИЯ.система;
}

/**
 * Значение атрибута `data-theme` на <html>.
 * Для системной темы атрибута нет вовсе: тогда решает `prefers-color-scheme`.
 */
export function атрибут(тема) {
  if (тема === 'день') return 'light';
  if (тема === 'ночь') return 'dark';
  return null;
}

/**
 * Собирает переключатель. Хранилище и корень передаются снаружи, чтобы
 * поведение можно было проверить без браузера.
 */
export function createTema({ storage = safeStorage(), root, button } = {}) {
  let тема = прочитать(storage);

  function применить() {
    const значение = атрибут(тема);
    if (root) {
      if (значение) root.setAttribute('data-theme', значение);
      else root.removeAttribute('data-theme');
    }
    if (button) {
      button.textContent = подпись(тема);
      button.setAttribute('aria-label', пояснение(тема));
      button.setAttribute('title', пояснение(тема));
    }
  }

  применить();

  button?.addEventListener('click', () => {
    тема = следующая(тема);
    try {
      storage?.setItem(КЛЮЧ, тема);
    } catch {
      /* приватное окно: тема сработает, но не запомнится */
    }
    применить();
  });

  return { текущая: () => тема, применить };
}

function прочитать(storage) {
  try {
    const значение = storage?.getItem(КЛЮЧ);
    return ТЕМЫ.includes(значение) ? значение : 'система';
  } catch {
    return 'система';
  }
}

function safeStorage() {
  try {
    return globalThis.localStorage ?? null;
  } catch {
    return null;
  }
}
