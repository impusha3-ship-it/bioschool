import * as rest from '../api/firebase-rest.js';
import { SCHOOL_ID } from '../firebase-config.js';
import { ПУСТО, начислить, итог } from './core.js';
import { неделя as неделяИз } from './weeks.js';

const ROOT = `schools/${SCHOOL_ID}`;
const KEY = 'bioschool.progress';

/**
 * Хранение прогресса и перенос его в базу.
 *
 * Считается всегда локально и сразу: гость набирает баллы с первого действия,
 * а вошедший ученик не ждёт сети, чтобы увидеть «+15». В базу то же состояние
 * уходит следом и молча — если не ушло, локальное остаётся, и при следующем
 * заходе всё сольётся.
 */
export function createProgress({
  api = rest,
  storage = globalThis.localStorage,
  сессия = () => null,
  токен = async () => null,
  now = () => new Date(),
} = {}) {
  function read() {
    try {
      const raw = storage.getItem(KEY);
      const данные = raw ? JSON.parse(raw) : null;
      return { ...ПУСТО, ...(данные ?? {}) };
    } catch {
      // Испорченная запись — не повод терять экран. Считаем, что начали заново.
      return { ...ПУСТО };
    }
  }

  function сохранить(состояние) {
    try {
      storage.setItem(KEY, JSON.stringify(состояние));
    } catch {
      // Переполненное или запрещённое хранилище: баллы потеряются, урок — нет.
    }
    return состояние;
  }

  /** Единственное, что зовут страницы. */
  async function record(событие) {
    const было = read();

    // Последний рубеж, а не способ прятать ошибки: `начислить` намеренно
    // падает на негодном событии (неизвестный kind, нет lessonId) — это
    // верно для тестов и разработки, где такое исключение обязано быть
    // громким. Но в браузере ученик к этому моменту уже прошёл игру, и
    // ценой необработанного исключения был бы сорванный урок, а не баг в
    // консоли. Поэтому здесь исключение гасится, хранилище не трогается,
    // а сам отказ ядра как был, так и остаётся ловиться тестами core.js.
    let подсчитано;
    try {
      подсчитано = начислить(было, событие, now());
    } catch {
      return { добавлено: 0, значки: [], состояние: было };
    }

    const { состояние, добавлено } = подсчитано;
    сохранить(состояние);

    const значки = новыеЗначки(было, состояние);
    отправитьПозже();

    return { добавлено, значки, состояние };
  }

  /**
   * Что показать плашкой: значки, которых минуту назад не было.
   *
   * Курсы сюда намеренно не передаются, хотя `итог` их принимает: значки
   * «Раздел закрыт» и «Год закрыт» из-за этого никогда не всплывут плашкой
   * прямо на начислении — тащить курс в каждый вызов `record` ради двух
   * значков дороже, чем они стоят. Увидеть их можно на странице прогресса,
   * где курсы и так уже загружены. Это не забытый случай, а выбор.
   */
  function новыеЗначки(было, стало) {
    const прежние = new Set(итог(было, [], now()).значки.filter((з) => з.есть).map((з) => з.id));
    return итог(стало, [], now())
      .значки.filter((з) => з.есть && !прежние.has(з.id));
  }

  async function отправить(состояние) {
    const s = сессия();
    if (!s?.studentId) return null;
    const token = await токен();
    if (!token) return null;

    // Пишем в ветку game, а не в корень записи: в корне живёт practice.
    await api.dbPut(`${ROOT}/progress/${s.studentId}/game`, состояние, { token });
    if (s.classId) {
      await api.dbPut(`${ROOT}/leaderboard/${s.classId}/${s.studentId}`, выжимка(состояние, now()), { token });
    }
    return состояние;
  }

  // Пока одна отправка ждала сети, могло прийти следующее начисление — если
  // не сериализовать, второй dbPut способен прийти на сервер раньше первого,
  // и в базе останется состояние старее локального. Поэтому отправки идут
  // строго друг за другом по очереди.
  //
  // Каждая отправка при этом берёт состояние заново через read(), а не то,
  // что было на момент постановки в очередь: пока она ждала своей очереди,
  // могло записаться более новое, и слать устаревший снимок нет смысла —
  // в базу должно уйти то, что видно прямо сейчас.
  let очередь = Promise.resolve();
  function отправитьПозже() {
    очередь = очередь.then(() => отправить(read())).catch(() => {
      // Отказ сети не должен ронять очередь для следующих отправок и не
      // должен быть виден ученику: локальный прогресс уже посчитан и
      // сохранён, база нагонит при следующей успешной попытке.
    });
    return очередь;
  }

  /**
   * Перенос при входе. Зовётся при каждом запуске с сессией ученика, и это
   * не расточительство: слияние берёт наибольшее, поэтому повторный вызов
   * ничего не меняет. Заодно на новом устройстве прогресс приезжает сам —
   * отдельного «скачать» не нужно, оно же и есть перенос.
   */
  async function перенести() {
    const s = сессия();
    if (!s?.studentId) return null;
    const token = await токен();
    if (!token) return null;

    let облачное = null;
    try {
      облачное = await api.dbGet(`${ROOT}/progress/${s.studentId}/game`, { token });
    } catch {
      // Нет доступа или нет связи — остаёмся на локальном, попробуем в другой
      // раз. Затирать локальное пустотой тут нельзя: это стёрло бы ученику всё
      // накопленное ровно в тот момент, когда у него пропал интернет.
      return null;
    }

    const слитое = слить(read(), облачное);
    сохранить(слитое);

    // Через очередь, а не напрямую: в ней может висеть отправка от только что
    // законченной игры, и два запроса вперегонки — ровно та беда, ради которой
    // очередь заводилась.
    await отправитьПозже();
    return слитое;
  }

  /**
   * Общая шкала класса и трое лучших за неделю.
   *
   * Цель считается сама: сколько учеников на сколько заданных уроков. Задавать
   * её руками не нужно, и она растёт вместе с курсом.
   *
   * Список класса берётся из `students`, а не из самой таблицы: таблица открыта
   * на чтение всем, и опираться на неё как на список — значит верить тому, что
   * туда написали. Правила базы чужую строку не пустят, но проверка списком
   * дешевле доверия.
   */
  async function шкалаКласса(classId) {
    if (!classId) return null;

    const [таблица, ученики, назначения] = await Promise.all([
      api.dbGet(`${ROOT}/leaderboard/${classId}`).catch(() => null),
      api.dbGet(`${ROOT}/students`).catch(() => null),
      api.dbGet(`${ROOT}/assignments/${classId}`).catch(() => null),
    ]);

    const свои = Object.entries(ученики ?? {}).filter(([, у]) => у.classId === classId);
    const строки = свои.map(([id, у]) => ({ id, имя: у.name, ...(таблица?.[id] ?? {}) }));
    const текущая = неделяИз(now());

    return {
      пройдено: строки.reduce((n, с) => n + число(с.lessonsDone), 0),
      цель: свои.length * Object.keys(назначения ?? {}).length,
      герои: строки
        .filter((с) => с.weekId === текущая && число(с.weekXp) > 0)
        .sort((a, b) => число(b.weekXp) - число(a.weekXp))
        .slice(0, 3)
        .map((с) => ({ имя: с.имя, xp: число(с.weekXp) })),
    };
  }

  return {
    read,
    record,
    перенести,
    шкалаКласса,
    // Точка входа для тестов — так же, как «Точки входа для тестов и
    // будущего управления с клавиатуры» в js/games/lab.js: без неё тест не
    // может дождаться, пока фоновая отправка в очереди действительно уйдёт.
    дождатьсяОтправки: () => очередь,
  };
}

/**
 * Слияние локального и облачного: по каждому виду работы берётся лучшее.
 * Складывать нельзя — одна и та же игра, пройденная на двух устройствах,
 * дала бы двойные баллы.
 */
export function слить(a, b) {
  const первое = { ...ПУСТО, ...(a ?? {}) };
  const второе = { ...ПУСТО, ...(b ?? {}) };

  const lessons = {};
  for (const id of ключи(первое.lessons, второе.lessons)) {
    const x = первое.lessons[id] ?? {};
    const y = второе.lessons[id] ?? {};
    const урок = {};
    for (const вид of ключи(x, y)) {
      if (вид === 'done') урок.done = Boolean(x.done || y.done);
      else урок[вид] = Math.max(число(x[вид]), число(y[вид]));
    }
    урок.done = Boolean(урок.done);
    lessons[id] = урок;
  }

  const weeks = {};
  for (const w of ключи(первое.weeks, второе.weeks)) {
    weeks[w] = Math.max(число(первое.weeks[w]), число(второе.weeks[w]));
  }

  // Результат раскладывается поверх обоих источников, а не собирается
  // литералом с руками перечисленными полями: иначе верхнеуровневое поле
  // будущей версии, о котором это слияние ещё не знает, молча исчезло бы —
  // ровно от этого предостерегает соседний `клон` в ядре. Версия берётся
  // наибольшая из двух, а не жёстко 1: слияние не имеет права понижать её.
  //
  // Поверх кладётся тот источник, который свежее по lastSeen, а не тот, что
  // стоит вторым доводом. Иначе слияние незнакомого поля зависело бы от
  // порядка вызова: `слить(своё, чужое)` и `слить(чужое, своё)` дали бы
  // разное, и место вызова молча решало бы, чей черновик выживет.
  const свежее = число(второе.lastSeen) >= число(первое.lastSeen) ? второе : первое;
  const прежнее = свежее === второе ? первое : второе;

  return {
    ...прежнее,
    ...свежее,
    v: Math.max(Number.isFinite(первое.v) ? первое.v : 1, Number.isFinite(второе.v) ? второе.v : 1),
    lessons,
    weeks,
    lastSeen: Math.max(число(первое.lastSeen), число(второе.lastSeen)),
  };
}

/** Число или ноль: испорченное значение из базы не должно превращаться в NaN. */
function число(v) {
  return Number.isFinite(v) ? v : 0;
}

/** Короткая открытая выжимка для шкалы класса и героев недели. */
export function выжимка(состояние, дата = new Date()) {
  const свод = итог(состояние, [], дата);
  const текущая = неделяИз(дата);
  return {
    xp: свод.xp,
    weekId: текущая,
    weekXp: состояние.weeks?.[текущая] ?? 0,
    lessonsDone: свод.уроки.пройдено,
    lastSeen: состояние.lastSeen ?? 0,
  };
}

function ключи(a = {}, b = {}) {
  return new Set([...Object.keys(a), ...Object.keys(b)]);
}
