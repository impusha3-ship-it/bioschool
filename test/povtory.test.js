import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

/*
  Одно и то же задание не должно стоять и в тренажёре, и в домашке одного
  урока.

  Зачем это правило. Тренажёр — место, где ошибиться бесплатно, и ученик
  проходит его перед домашкой. Если формулировка та же, домашка перестаёт
  что-либо проверять: ответ не вспоминают, а узнают. Решение учителя от
  6 сентября 2026 года.

  Почему проверка ловит только дословные совпадения. Похожесть текстов тут
  не работает: у законных пар «то же задание, другие данные» она ВЫШЕ, чем
  у настоящих повторов. Замерено на живом материале:

    паспорт сосны / паспорт ели          — 0,76 и это норма
    «подпиши, что изображено» ×2         — 0,78 и это норма
    зона по условиям: тайга / тундра     — 0,48 и это норма
    «почему пластик не разлагается» ×2   — 0,38 и это повтор

  Такие пары — костяк настоящей работы: один тип задания отрабатывается на
  разных объектах, и запрещать это значит запрещать тренировку. Отличает
  повтор от тренировки только смысл, а его меряет человек, не тест.

  Поэтому здесь стоит пол, а не потолок: дословное совпадение — заведомая
  ошибка, и её держит машина. За переформулированными повторами следит
  человек; список законных пар и разбор — в STATUS, раздел «Повторы».
*/

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIR = join(ROOT, 'content', 'lessons');

/** Приводит формулировку к сравнимому виду: регистр, ё, знаки, пробелы. */
export function сличить(текст) {
  return String(текст ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim();
}

/**
 * Чем задание отличается от другого.
 *
 * Одного текста мало. У заданий «подпиши, что изображено» и «что выпадает из
 * общего ряда» текст один и тот же во всех уроках — всё содержание лежит в
 * фотографиях, и на разных снимках это разные задания с разными ответами.
 * Поэтому в ключ идут ещё и имена файлов картинок.
 *
 * А вот ответ в ключ не идёт намеренно. Восемь повторов, ради которых
 * проверка и написана, были устроены именно так: вопрос слово в слово тот же,
 * а варианты ответа переписаны другими словами. Ученик узнаёт задание по
 * вопросу, а не по вариантам, — значит и сличать надо вопрос.
 */
function ключ(q, текст) {
  const картинки = (q.figures ?? []).map((ф) => ф.src ?? '').join(',');
  return `${сличить(текст)}||${картинки}`;
}

/** Все формулировки урока с указанием, где именно они стоят. */
function формулировки(урок) {
  const out = [];
  for (const q of урок.vpr ?? []) {
    out.push({ зона: 'тренажёр', id: q.id, текст: q.text, ключ: ключ(q, q.text) });
  }
  for (const q of урок.homework?.questions ?? []) {
    out.push({ зона: 'домашка', id: q.id, текст: q.text, ключ: ключ(q, q.text) });
  }
  for (const q of урок.homework?.open ?? []) {
    out.push({ зона: 'домашка', id: q.id, текст: q.prompt, ключ: ключ(q, q.prompt) });
  }
  return out.filter((з) => сличить(з.текст).length > 0);
}

async function всеУроки() {
  const файлы = (await readdir(DIR)).filter((ф) => ф.endsWith('.json')).sort();
  const уроки = [];
  for (const файл of файлы) {
    уроки.push({ файл, урок: JSON.parse(await readFile(join(DIR, файл), 'utf8')) });
  }
  return уроки;
}

const уроки = await всеУроки();

test('формулировка не повторяется между тренажёром и домашкой урока', () => {
  const беды = [];

  for (const { файл, урок } of уроки) {
    const поТексту = new Map();
    for (const з of формулировки(урок)) {
      поТексту.set(з.ключ, [...(поТексту.get(з.ключ) ?? []), з]);
    }

    for (const [, места] of поТексту) {
      const зоны = new Set(места.map((м) => м.зона));
      if (места.length > 1 && зоны.size > 1) {
        беды.push(`${файл}: ${места.map((м) => `${м.зона}/${м.id}`).join(' = ')}`);
      }
    }
  }

  assert.deepEqual(
    беды,
    [],
    'одно и то же задание стоит и в тренажёре, и в домашке — ' +
      'перепиши задание домашки на другой вопрос по той же теме:\n  ' +
      беды.join('\n  '),
  );
});

test('формулировка не повторяется внутри одной зоны урока', () => {
  const беды = [];

  for (const { файл, урок } of уроки) {
    for (const зона of ['тренажёр', 'домашка']) {
      const поТексту = new Map();
      for (const з of формулировки(урок).filter((з) => з.зона === зона)) {
        поТексту.set(з.ключ, [...(поТексту.get(з.ключ) ?? []), з.id]);
      }
      for (const [, ид] of поТексту) {
        if (ид.length > 1) беды.push(`${файл}, ${зона}: ${ид.join(' = ')}`);
      }
    }
  }

  assert.deepEqual(беды, [], `задание стоит дважды в одном месте:\n  ${беды.join('\n  ')}`);
});

/*
  Задание из одного урока не должно всплыть в другом. Формулировки в каталоге
  ВПР повторяются из года в год почти дословно, и одно и то же задание легко
  поставить дважды в разные уроки — ученик замечает это сразу и перестаёт
  верить тренажёру.
*/
test('задание не повторяется в разных уроках', () => {
  const поТексту = new Map();

  for (const { файл, урок } of уроки) {
    for (const з of формулировки(урок)) {
      поТексту.set(з.ключ, [...(поТексту.get(з.ключ) ?? []), `${файл}/${з.id}`]);
    }
  }

  const беды = [];
  for (const [, места] of поТексту) {
    const файлы = new Set(места.map((м) => м.split('/')[0]));
    if (файлы.size > 1) беды.push(места.join(' = '));
  }

  assert.deepEqual(беды, [], `одно задание в разных уроках:\n  ${беды.join('\n  ')}`);
});
