/**
 * Пересчёт таблицы почёта по сданным домашним работам.
 *
 * Общий для скрипта `scripts/pereschet-pochyota.mjs` и панели учителя,
 * которая сверяет почёт сама при открытии: считать одно и то же двумя
 * разными кусками кода значило бы однажды получить два разных почёта.
 *
 * Считается всё из `submissions` — из того, что ученик вправду сдал, а не из
 * его прогресса: прогресс ученик пишет себе сам, а работы принимает база по
 * своим правилам, и первая попытка в ней одна. Цена работы берётся из той же
 * `ценность`, что считает баллы на сайте.
 */
import { ценность } from '../progress/core.js';
import { неделя } from '../progress/weeks.js';

/**
 * Домашние баллы одного ученика: за всё время и за текущую неделю.
 *
 * Неделя берётся по времени сдачи, а не по времени пересчёта: работа, сданная
 * в понедельник, должна попасть в эту неделю, даже если пересчитали в пятницу.
 */
export function домашниеБаллы(работы = {}, сейчас = new Date()) {
  const текущая = неделя(сейчас);
  let всего = 0;
  let заНеделю = 0;

  for (const работа of Object.values(работы ?? {})) {
    if (!работа?.submittedAt) continue;
    const баллы = ценность({ kind: 'homework', percent: работа.percent ?? 0 });
    всего += баллы;
    if (неделя(new Date(работа.submittedAt)) === текущая) заНеделю += баллы;
  }

  return { hwXp: всего, hwWeekXp: заНеделю };
}

/**
 * Что пересчёт изменит. Ничего не пишет — только перечисляет.
 *
 * `изменения` — строки, где числа разошлись; `безСтроки` — ученики со
 * сданными работами, у которых строки в таблице нет. Заводить её здесь
 * нельзя: правила требуют в строке `xp` и `weekId`, а взять их неоткуда.
 * Строка появится сама, как только ученик что-нибудь сделает на сайте.
 */
export function планПересчёта({ students = {}, submissions = {}, leaderboard = {}, сейчас = new Date() } = {}) {
  const изменения = [];
  const безСтроки = [];

  for (const [id, ученик] of Object.entries(students ?? {})) {
    const стало = домашниеБаллы(submissions?.[id], сейчас);
    const строка = leaderboard?.[ученик.classId]?.[id];

    if (!строка) {
      if (стало.hwXp > 0) безСтроки.push({ id, имя: ученик.name, hwXp: стало.hwXp });
      continue;
    }

    if (строка.hwXp === стало.hwXp && строка.hwWeekXp === стало.hwWeekXp) continue;

    изменения.push({
      id,
      classId: ученик.classId,
      имя: ученик.name,
      было: { hwXp: строка.hwXp ?? null, hwWeekXp: строка.hwWeekXp ?? null },
      стало,
    });
  }

  изменения.sort((a, b) => a.имя.localeCompare(b.имя, 'ru'));
  return { изменения, безСтроки };
}
