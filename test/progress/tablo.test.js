import { test } from 'node:test';
import assert from 'node:assert/strict';
import { собратьТабло } from '../../js/pages/tablo.js';

const НЕДЕЛЯ = '2026-W36';

const ДАННЫЕ = {
  classes: { '7a': { title: '7А', grade: 7 }, '5b': { title: '5Б', grade: 5 } },
  students: {
    s1: { name: 'Алёшин Юрий', classId: '7a' },
    s2: { name: 'Баранец София', classId: '7a' },
    s3: { name: 'Губин Илья', classId: '7a' },
    s4: { name: 'Заец Алиса', classId: '5b' },
  },
  /*
    В строке два счёта: `xp` — весь прогресс ученика, по нему учитель видит
    ступень; `hwXp` — только сданные домашние работы. Почёт строится по
    второму, и цифры здесь нарочно разные: перепутай их код — и тест увидит.
    Работа стоит не больше 40 (30 и бонус 10). Успешность по школе — из
    заданного: 7А задано две работы (максимум 80), 5Б — одна (40).
    Губин 80 — 100%, Алёшин 60 — 75%, Заец 20 — 50%, Баранец 35 из 80 — 44%:
    одну работу она не сдала.
  */
  leaderboard: {
    '7a': {
      s1: { xp: 900, hwXp: 60, hwDone: 2, weekId: НЕДЕЛЯ, weekXp: 200, hwWeekXp: 30, hwWeekDone: 1, lessonsDone: 4 },
      s2: { xp: 200, hwXp: 35, hwDone: 1, weekId: НЕДЕЛЯ, weekXp: 100, hwWeekXp: 35, hwWeekDone: 1, lessonsDone: 2 },
      s3: { xp: 800, hwXp: 80, hwDone: 2, weekId: '2026-W35', weekXp: 90, hwWeekXp: 40, hwWeekDone: 1, lessonsDone: 6 },
    },
    '5b': { s4: { xp: 250, hwXp: 20, hwDone: 1, weekId: НЕДЕЛЯ, weekXp: 80, hwWeekXp: 20, hwWeekDone: 1, lessonsDone: 3 } },
  },
  assignments: { '7a': { u1: {}, u2: {} }, '5b': { u1: {} } },
};

const собрать = (данные = ДАННЫЕ) => собратьТабло({ ...данные, неделя: НЕДЕЛЯ });

// ── Школа: по успешности ────────────────────────────────────

test('школьная тройка — по успешности из заданного, по всей школе', () => {
  const { всегда } = собрать().школа;
  assert.deepEqual(всегда.map((с) => с.имя), ['Губин Илья', 'Алёшин Юрий', 'Заец Алиса']);
  assert.deepEqual(всегда.map((с) => с.процент), [100, 75, 50]);
  assert.equal(всегда[0].класс, '7А', 'рядом с именем должен стоять класс');
});

test('общая тройка не растягивается на всех, у кого есть работы', () => {
  const { всегда } = собрать().школа;
  assert.equal(всегда.length, 3);
  assert.equal(всегда.some((с) => с.имя === 'Баранец София'), false, 'четвёртая: одна работа не сдана');
});

/*
  Решение учителя от 17 сентября 2026: классам задают разное число работ,
  и по сумме школьную тройку занимал тот класс, которому задали больше.
  Здесь восьмикласснику задано пять работ, пятикласснице — две.
*/
test('класс, которому задали больше, не выигрывает количеством', () => {
  const данные = {
    classes: { 5: { title: '5' }, 8: { title: '8' } },
    students: { a: { name: 'Пятиклассница', classId: '5' }, b: { name: 'Восьмиклассник', classId: '8' } },
    leaderboard: {
      5: { a: { hwXp: 80, hwDone: 2, weekId: НЕДЕЛЯ } },
      8: { b: { hwXp: 150, hwDone: 5, weekId: НЕДЕЛЯ } },
    },
    assignments: { 5: { u1: {}, u2: {} }, 8: { u1: {}, u2: {}, u3: {}, u4: {}, u5: {} } },
  };
  const { всегда } = собрать(данные).школа;
  assert.deepEqual(всегда.map((с) => с.имя), ['Пятиклассница', 'Восьмиклассник']);
  assert.deepEqual(всегда.map((с) => с.процент), [100, 75]);
});

/*
  Случай, с которого началось (17 сентября 2026): ученица сдала три работы из
  пяти заданных, все на сто процентов, и стояла в школьной тройке первой.
  Несданная работа — ноль: процент считается из заданного, а не из сданного.
*/
test('несданная работа считается нулём', () => {
  const данные = {
    classes: { 8: { title: '8' } },
    students: { a: { name: 'Три из пяти на отлично', classId: '8' }, b: { name: 'Все пять похуже', classId: '8' } },
    leaderboard: { 8: { a: { hwXp: 120, hwDone: 3 }, b: { hwXp: 150, hwDone: 5 } } },
    assignments: { 8: { u1: {}, u2: {}, u3: {}, u4: {}, u5: {} } },
  };
  const { всегда } = собрать(данные).школа;
  assert.deepEqual(всегда.map((с) => с.имя), ['Все пять похуже', 'Три из пяти на отлично']);
  assert.deepEqual(всегда.map((с) => с.процент), [75, 60]);
});

test('при равной успешности выше тот, кто сдал больше', () => {
  const данные = {
    classes: { 8: { title: '8' } },
    students: { a: { name: 'Аксёнова', classId: '8' }, b: { name: 'Борисов', classId: '8' } },
    leaderboard: { 8: { a: { hwXp: 60, hwDone: 2 }, b: { hwXp: 60, hwDone: 3 } } },
    assignments: { 8: { u1: {}, u2: {}, u3: {} } },
  };
  assert.deepEqual(собрать(данные).школа.всегда.map((с) => с.имя), ['Борисов', 'Аксёнова']);
});

// Старые строки числа сданных работ не несут. За всё время это не мешает —
// процент считается из заданного; за неделю без него делить не на что, и
// строка ждёт, пока панель учителя не допишет число.
test('строка без числа сданных работ считается по заданному, а в неделю не встаёт', () => {
  const данные = { ...ДАННЫЕ, leaderboard: { '7a': { s1: { hwXp: 60, weekId: НЕДЕЛЯ, hwWeekXp: 30 } } } };
  const { всегда, неделя } = собрать(данные).школа;
  assert.deepEqual(всегда.map((с) => с.процент), [75]);
  assert.deepEqual(неделя, []);
});

// За неделю — из заданного на этой неделе. Доделанная старая работа
// процент выше ста не поднимает.
test('за неделю процент считается из заданного на этой неделе', () => {
  const вСреду = new Date(2026, 8, 2).getTime(); // 36-я неделя
  const раньше = new Date(2026, 7, 20).getTime();
  const данные = {
    classes: { 8: { title: '8' } },
    students: {
      a: { name: 'Одна из двух', classId: '8' },
      b: { name: 'Обе', classId: '8' },
      c: { name: 'Доделал старую', classId: '8' },
    },
    leaderboard: { 8: {
      a: { hwXp: 40, hwDone: 1, weekId: НЕДЕЛЯ, hwWeekXp: 40, hwWeekDone: 1 },
      b: { hwXp: 60, hwDone: 2, weekId: НЕДЕЛЯ, hwWeekXp: 60, hwWeekDone: 2 },
      c: { hwXp: 120, hwDone: 3, weekId: НЕДЕЛЯ, hwWeekXp: 120, hwWeekDone: 3 },
    } },
    assignments: { 8: { u1: { assignedAt: раньше }, u2: { assignedAt: вСреду }, u3: { assignedAt: вСреду } } },
  };
  const { неделя } = собрать(данные).школа;
  assert.deepEqual(неделя.map((с) => [с.имя, с.процент]), [
    ['Доделал старую', 100],
    ['Обе', 75],
    ['Одна из двух', 50],
  ]);
});

/*
  Недельная строка живёт до конца недели, а потом устаревает: в базе у неё
  остаётся прошлый weekId. Не отсечь его — и в понедельник на табло висели
  бы прошлонедельные победители, которых уже никто не догоняет.
*/
test('в школьных героях недели только строки текущей недели, по успешности', () => {
  const { неделя } = собрать().школа;
  assert.deepEqual(неделя.map((с) => с.имя), ['Баранец София', 'Алёшин Юрий', 'Заец Алиса']);
  assert.equal(неделя.some((с) => с.имя === 'Губин Илья'), false, 'его строка — с прошлой недели');
});

test('нули в героях недели не показываются', () => {
  const данные = { ...ДАННЫЕ, leaderboard: { '7a': { s1: { hwXp: 10, hwDone: 1, weekId: НЕДЕЛЯ, hwWeekXp: 0, hwWeekDone: 0 } } } };
  assert.deepEqual(собрать(данные).школа.неделя, []);
});

/*
  Решение учителя от 16 сентября 2026: в почёт идут только домашние работы.
  Тренажёр открыт всем и всегда, домашку задаёт учитель и сдаётся она один раз;
  считай общую сумму — и впереди окажется тот, у кого больше свободного времени.
*/
test('игры и тренажёр в таблицу почёта не идут', () => {
  const данные = {
    ...ДАННЫЕ,
    leaderboard: {
      '7a': {
        s1: { xp: 9000, hwXp: 0, hwDone: 0, weekId: НЕДЕЛЯ, weekXp: 9000, hwWeekXp: 0, hwWeekDone: 0 },
        s2: { xp: 30, hwXp: 30, hwDone: 1, weekId: НЕДЕЛЯ, weekXp: 30, hwWeekXp: 30, hwWeekDone: 1 },
      },
    },
  };
  const { школа, классы } = собрать(данные);
  const седьмой = классы.find((к) => к.id === '7a');

  assert.deepEqual(школа.всегда.map((с) => с.имя), ['Баранец София'], 'прошедший все игры мимо почёта');
  assert.deepEqual(школа.неделя.map((с) => с.имя), ['Баранец София']);
  assert.deepEqual(седьмой.всегда.map((с) => с.имя), ['Баранец София']);
});

// ── Класс: по сумме ─────────────────────────────────────────

test('внутри класса по-прежнему сумма домашних баллов, а не общий счёт', () => {
  const седьмой = собрать().классы.find((к) => к.id === '7a');
  assert.deepEqual(седьмой.всегда.map((с) => с.имя), ['Губин Илья', 'Алёшин Юрий', 'Баранец София']);
  assert.deepEqual(седьмой.всегда.map((с) => с.xp), [80, 60, 35], 'у Губина 800 общих и 80 домашних');
  assert.equal(седьмой.всегда.some((с) => с.classId !== '7a'), false, 'чужих в тройке класса нет');
});

test('в тройке класса не больше трёх', () => {
  const данные = {
    ...ДАННЫЕ,
    students: { ...ДАННЫЕ.students, s5: { name: 'Ким Лев', classId: '7a' } },
    leaderboard: {
      ...ДАННЫЕ.leaderboard,
      '7a': { ...ДАННЫЕ.leaderboard['7a'], s5: { xp: 1, hwXp: 10, hwDone: 1, weekId: НЕДЕЛЯ } },
    },
  };
  const седьмой = собрать(данные).классы.find((к) => к.id === '7a');
  assert.equal(седьмой.всегда.length, 3);
});

test('по каждому классу свой счёт и свои герои', () => {
  const классы = собрать().классы;
  const седьмой = классы.find((к) => к.id === '7a');

  assert.equal(седьмой.title, '7А');
  // Герои недели в классе — по сумме за неделю.
  assert.deepEqual(седьмой.неделя.map((с) => с.имя), ['Баранец София', 'Алёшин Юрий']);
  // Задано: трое учеников на два заданных урока. Сдано — по числу сданных
  // работ, а не по урокам, пройденным в тренажёре (их у класса 12).
  assert.equal(седьмой.задано, 6);
  assert.equal(седьмой.сдано, 5);
  assert.equal(седьмой.процент, 83);
});

test('класс без заданных уроков не делит на ноль', () => {
  const данные = { ...ДАННЫЕ, assignments: {} };
  const { классы } = собрать(данные);
  const седьмой = классы.find((к) => к.id === '7a');
  assert.equal(седьмой.задано, 0);
  assert.equal(седьмой.процент, 0);
});

// Строку в таблице пишет сам ученик, и таблица открыта на чтение всем.
// Опираться на неё как на список — значит верить тому, что туда написали.
test('чужие строки в таблице на табло не попадают', () => {
  const данные = {
    ...ДАННЫЕ,
    leaderboard: {
      '7a': {
        ...ДАННЫЕ.leaderboard['7a'],
        самозванец: { xp: 9999, hwXp: 9999, hwDone: 1, weekId: НЕДЕЛЯ, weekXp: 9999, hwWeekXp: 9999, hwWeekDone: 1 },
      },
    },
  };
  const { школа, классы } = собрать(данные);
  const все = [...школа.всегда, ...школа.неделя, ...классы.flatMap((к) => [...к.всегда, ...к.неделя])];
  assert.equal(все.some((с) => с.id === 'самозванец'), false);
});

test('пустая база даёт пустое табло, а не ошибку', () => {
  const пусто = собратьТабло({ неделя: НЕДЕЛЯ });
  assert.deepEqual(пусто.школа.всегда, []);
  assert.deepEqual(пусто.школа.неделя, []);
  assert.deepEqual(пусто.классы, []);
});

test('ученик без единого балла в списки не лезет', () => {
  const данные = { ...ДАННЫЕ, leaderboard: {} };
  assert.deepEqual(собрать(данные).школа.всегда, []);
  const седьмой = собрать(данные).классы.find((к) => к.id === '7a');
  assert.equal(седьмой.сдано, 0);
  assert.deepEqual(седьмой.всегда, []);
});
