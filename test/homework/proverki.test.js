import { test } from 'node:test';
import assert from 'node:assert/strict';
import { новыеПроверки, меткаПроверки, createПроверки } from '../../js/homework/proverki.js';

/*
  Развёрнутый ответ — единственная оценка, которая приходит не сразу. Ошибиться
  здесь можно двумя способами, и оба плохие: промолчать о проверке (ученик так и
  не узнает балл) или повторять уведомление на каждом заходе. Поэтому проверяется
  ровно граница между «новое» и «уже видел».
*/

const сессия = () => ({ studentId: 's1', classId: '5a' });

test('проверенная работа, о которой не говорили, — новость', () => {
  const новые = новыеПроверки(
    { u1: { manualScore: 2, checkedAt: 500, comment: 'Молодец' } },
    {},
  );
  assert.deepEqual(новые, [{ lessonId: 'u1', manualScore: 2, comment: 'Молодец', метка: 500 }]);
});

test('о прочитанной проверке второй раз не говорят', () => {
  const новые = новыеПроверки({ u1: { manualScore: 2, checkedAt: 500 } }, { u1: 500 });
  assert.deepEqual(новые, []);
});

// Балл теперь можно переправить, и переправленный — такая же новость, как первый.
test('переправленный балл уведомляет заново', () => {
  const новые = новыеПроверки({ u1: { manualScore: 3, checkedAt: 900 } }, { u1: 500 });
  assert.equal(новые.length, 1);
  assert.equal(новые[0].manualScore, 3);
});

test('непроверенная работа не уведомляет', () => {
  assert.deepEqual(новыеПроверки({ u1: { open: { o: 'ждёт' }, submittedAt: 1 } }, {}), []);
});

// Ноль — это оценка, и узнать про неё ученик должен так же, как про тройку.
test('ноль баллов уведомляет наравне с остальными', () => {
  assert.equal(новыеПроверки({ u1: { manualScore: 0, checkedAt: 5 } }, {}).length, 1);
});

/*
  Работы, проверенные до появления уведомлений, времени проверки не имеют.
  Промолчать о них нельзя — балл ученику так и не показывали, — но и повторять
  такое уведомление вечно тоже нельзя.
*/
test('проверка без времени уведомляет один раз', () => {
  const работа = { u1: { manualScore: 1 } };
  assert.equal(новыеПроверки(работа, {}).length, 1);
  assert.equal(меткаПроверки(работа.u1), 1);
  assert.equal(новыеПроверки(работа, { u1: меткаПроверки(работа.u1) }).length, 0);
});

test('свежая проверка идёт первой', () => {
  const новые = новыеПроверки(
    { u1: { manualScore: 1, checkedAt: 100 }, u2: { manualScore: 2, checkedAt: 900 } },
    {},
  );
  assert.deepEqual(новые.map((п) => п.lessonId), ['u2', 'u1']);
});

// ── Работа с базой ───────────────────────────────────────────

test('новое собирается из сданного и отметок о прочтении', async () => {
  const проверки = createПроверки({
    api: {
      dbGet: async (path) =>
        path.endsWith('/checks')
          ? { u1: 500 }
          : { u1: { manualScore: 2, checkedAt: 500 }, u2: { manualScore: 1, checkedAt: 700 } },
    },
    сессия,
    токен: async () => 'т',
  });

  const новые = await проверки.новое();
  assert.deepEqual(новые.map((п) => п.lessonId), ['u2']);
});

test('гостю уведомлять нечего и базу за этим не дёргают', async () => {
  let запросов = 0;
  const проверки = createПроверки({
    api: { dbGet: async () => { запросов += 1; return {}; } },
    сессия: () => null,
    токен: async () => 'т',
  });

  assert.deepEqual(await проверки.новое(), []);
  assert.equal(запросов, 0);
});

// Уведомление — не то, ради чего стоит показывать ученику ошибку сети.
test('без связи уведомлений просто нет', async () => {
  const проверки = createПроверки({
    api: { dbGet: async () => { throw new Error('Нет связи с сервером. Проверь интернет.'); } },
    сессия,
    токен: async () => 'т',
  });
  assert.deepEqual(await проверки.новое(), []);
});

test('прочитанное отмечается меткой той же проверки', async () => {
  const записи = [];
  const проверки = createПроверки({
    api: { dbPatch: async (path, value) => { записи.push({ path, value }); } },
    сессия,
    токен: async () => 'т',
  });

  await проверки.отметить([{ lessonId: 'u1', метка: 500 }, { lessonId: 'u2', метка: 700 }]);

  assert.match(записи[0].path, /progress\/s1\/checks$/);
  assert.deepEqual(записи[0].value, { u1: 500, u2: 700 });
});

test('отметка без сессии в базу не идёт', async () => {
  let было = false;
  const проверки = createПроверки({
    api: { dbPatch: async () => { было = true; } },
    сессия: () => null,
    токен: async () => 'т',
  });

  await проверки.отметить([{ lessonId: 'u1', метка: 1 }]);
  assert.equal(было, false);
});
