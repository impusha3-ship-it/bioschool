/**
 * Склонения. Вынесены из страницы прогресса, когда те же слова понадобились
 * в панели учителя: «164 баллов» на экране, который учитель показывает
 * ребёнку, читается как небрежность.
 */
export function баллов(n) {
  return выбрать(n, ['балл', 'балла', 'баллов']);
}

export function недель(n) {
  return выбрать(n, ['неделю', 'недели', 'недель']);
}

export function уроков(n) {
  return выбрать(n, ['урок', 'урока', 'уроков']);
}

/** Русское правило: 11–14 всегда во множественном, дальше по последней цифре. */
function выбрать(n, [один, мало, много]) {
  const число = Math.abs(Number(n) || 0);
  if (число % 100 >= 11 && число % 100 <= 14) return много;
  const остаток = число % 10;
  if (остаток === 1) return один;
  if (остаток >= 2 && остаток <= 4) return мало;
  return много;
}
