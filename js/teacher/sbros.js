/**
 * Что именно стирается при обнулении баллов класса.
 *
 * Вынесено из скрипта отдельной чистой функцией ради теста. Обнуление
 * необратимо и идёт по живой базе, где рядом лежат коды входа: допиши сюда
 * по невнимательности `secrets` — и весь класс останется без доступа, а
 * восстановить коды нельзя, в базе только их хеши. Тест перечисляет ветки
 * поимённо и не даст этому случиться молча.
 */

/** Пустая запись прогресса с пометкой времени сброса. */
export function чистыйПрогресс(сброс) {
  return { v: 1, lessons: {}, weeks: {}, lastSeen: 0, resetAt: сброс };
}

/**
 * План записей: по две на ученика — обнулённый прогресс и снятая строка
 * таблицы. Ничего больше трогать не полагается.
 */
export function планСброса({ root, classId, studentIds = [], сброс }) {
  const чистое = чистыйПрогресс(сброс);
  return studentIds.flatMap((id) => [
    { path: `${root}/progress/${id}/game`, value: чистое },
    { path: `${root}/leaderboard/${classId}/${id}`, value: null },
  ]);
}

/** Ветки, которые обнуление не имеет права трогать. */
export const НЕПРИКОСНОВЕННЫЕ = ['secrets', 'students', 'bindings', 'submissions', 'classes', 'assignments'];
