import { test } from 'node:test';
import assert from 'node:assert/strict';
import { ЗНАЧКИ } from '../../js/progress/core.js';
import { рисунокЗначка, ЕСТЬ_РИСУНОК } from '../../js/ui/znachki.js';

/*
  Новый значок легко завести и забыть нарисовать: без рисунка он молча
  получит росток от соседа, и на гербарном листе окажутся два одинаковых
  значка. Заметит это не программист, а ребёнок.
*/
test('у каждого значка есть свой рисунок', () => {
  for (const з of ЗНАЧКИ) {
    assert.ok(ЕСТЬ_РИСУНОК.includes(з.id), `нет рисунка для значка «${з.имя}» (${з.id})`);
  }
});

test('рисунки не повторяются', () => {
  const разметка = ЗНАЧКИ.map((з) => рисунокЗначка(з.id));
  assert.equal(new Set(разметка).size, разметка.length, 'два значка нарисованы одинаково');
});

test('лишних рисунков не остаётся', () => {
  const свои = new Set(ЗНАЧКИ.map((з) => з.id));
  for (const id of ЕСТЬ_РИСУНОК) {
    assert.ok(свои.has(id), `рисунок ${id} не принадлежит ни одному значку`);
  }
});

// Рисунок вставляется внутрь <svg> как есть, поэтому в нём не должно быть
// ничего, кроме фигур: чужой тег сломал бы разметку страницы молча.
test('в рисунке только фигуры', () => {
  for (const з of ЗНАЧКИ) {
    const разметка = рисунокЗначка(з.id);
    assert.match(разметка, /^<(path|circle|rect|line|ellipse|polyline|polygon)[\s>]/, `${з.id}: начинается не с фигуры`);
    assert.equal(/<(script|style|foreignObject|image)/i.test(разметка), false, `${з.id}: посторонний тег`);
  }
});
