import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

import { loadInventar } from '../js/content.js';

/*
  Значки инвентаря для сбора стола в лабораторной.

  Реестр `content/inventar.json` лежит отдельно от уроков: в файлах уроков
  оборудование осталось списком названий, и добавленный в реестр значок
  оживляет все работы сразу, без правки контента. Плата за это — названия
  должны совпадать слово в слово, и следит за этим здешняя проверка.

  Этап показывает картинки только там, где значок есть у ВСЕХ предметов полки.
  Полка наполовину из картинок, наполовину из слов хуже обеих: по картинке
  узнают прибор, а по слову рядом читают ответ. Поэтому «покрытых» работ
  может быть меньше, чем работ со значками, и это нормально.
*/

const ROOT = fileURLToPath(new URL('..', import.meta.url));

/*
  Работы, у которых полка ещё показывается названиями: значков хватает не на
  всё. Список может только уменьшаться — потолок его не пустит вырасти.
  Уменьшил список, нарезав значки, — уменьши и ПОТОЛОК.
*/
const БЕЗ_ЗНАЧКОВ = [
  '5-citologiya',
  '5-metod-opisaniya',
  '5-svoystva-organizmov',
  '7-golosemennye-hvoynye',
  '7-mhi-stroenie',
  '7-plauny-hvoshchi-paporotniki',
  '7-pokrytosemennye-stroenie',
  '7-zelenye-vodorosli',
];

const ПОТОЛОК = 8;

async function файлЕсть(...части) {
  try {
    await access(join(ROOT, ...части));
    return true;
  } catch {
    return false;
  }
}

/** Все полки инвентаря, какие есть в уроках: файл → список названий. */
async function полки() {
  const dir = join(ROOT, 'content', 'lessons');
  const найдено = [];

  for (const файл of (await readdir(dir)).filter((ф) => ф.endsWith('.json'))) {
    const урок = JSON.parse(await readFile(join(dir, файл), 'utf8'));
    for (const блок of урок.summary?.blocks ?? []) {
      const набор = блок.run?.equipment;
      if (!набор) continue;
      найдено.push({
        урок: файл.replace('.json', ''),
        предметы: [...(набор.need ?? []), ...(набор.extra ?? [])],
      });
    }
  }
  return найдено;
}

const реестр = JSON.parse(await readFile(join(ROOT, 'content', 'inventar.json'), 'utf8'));
const карта = await loadInventar({
  fetchFn: async () => ({ ok: true, json: async () => реестр }),
});
const всеПолки = await полки();

test('у каждого значка есть файл рисунка и описание для читалки', async () => {
  const приборы = Object.entries(реестр.приборы ?? {});
  assert.ok(приборы.length > 0, 'реестр пуст');

  for (const [название, запись] of приборы) {
    assert.ok(запись.рисунок, `${название}: не указан рисунок`);
    assert.ok(
      await файлЕсть('img', 'bio', запись.рисунок),
      `${название}: файла img/bio/${запись.рисунок} нет`,
    );
    // Прибор на полке не подписан, и для того, кто страницу слушает,
    // описание — единственный способ узнать, что на плитке.
    assert.ok(запись.alt?.length > 10, `${название}: нет внятного описания alt`);
  }
});

test('синонимы ведут на существующий прибор', () => {
  for (const [синоним, название] of Object.entries(реестр['то же самое'] ?? {})) {
    assert.ok(реестр.приборы?.[название], `«${синоним}» ведёт на неизвестный «${название}»`);
    assert.equal(карта.get(синоним)?.рисунок, реестр.приборы[название].рисунок);
  }
});

test('в реестре нет значков, которые нигде не нужны', () => {
  const нужны = new Set(всеПолки.flatMap((п) => п.предметы));
  const лишние = [...карта.keys()].filter((имя) => !нужны.has(имя));
  assert.deepEqual(
    лишние,
    [],
    `значки есть, а работы их не просят: ${лишние.join(', ')} — либо убрать, либо поставить в работу`,
  );
});

test('список работ без значков совпадает с действительностью', () => {
  const непокрытые = всеПолки
    .filter((п) => !п.предметы.every((имя) => карта.has(имя)))
    .map((п) => п.урок);

  assert.deepEqual(
    [...new Set(непокрытые)].sort(),
    [...БЕЗ_ЗНАЧКОВ].sort(),
    'список БЕЗ_ЗНАЧКОВ разошёлся с тем, что есть в уроках: нарезал значки — вычеркни работу и уменьши ПОТОЛОК',
  );
});

test('список работ без значков может только уменьшаться', () => {
  assert.ok(
    БЕЗ_ЗНАЧКОВ.length <= ПОТОЛОК,
    `работ без значков стало больше (${БЕЗ_ЗНАЧКОВ.length} против ${ПОТОЛОК}): ` +
      'новую работу собирают со значками, а не со списком названий',
  );
});

test('хотя бы одна работа собирается по картинкам', () => {
  const покрытые = всеПолки.filter((п) => п.предметы.every((имя) => карта.has(имя)));
  assert.ok(покрытые.length > 0, 'ни одна полка не покрыта значками целиком');
});

test('«Наблюдение и эксперимент» собирается по картинкам', () => {
  // Первая работа, переведённая на картинки. Проверка стережёт её отдельно:
  // случайно убранный значок иначе тихо вернул бы полку к названиям.
  const полка = всеПолки.find((п) => п.урок === '5-nablyudenie-i-eksperiment');
  assert.ok(полка, 'работа с полкой в этом уроке не нашлась');

  const без = полка.предметы.filter((имя) => !карта.has(имя));
  assert.deepEqual(без, [], `без значка остались: ${без.join(', ')}`);
});
