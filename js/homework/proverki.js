import * as rest from '../api/firebase-rest.js';
import { SCHOOL_ID } from '../firebase-config.js';

const ROOT = `schools/${SCHOOL_ID}`;

/**
 * Уведомления ученику о проверенных развёрнутых ответах.
 *
 * Развёрнутый ответ — единственное место, где оценка приходит не сразу:
 * машина его не судит, работу читает учитель, и между сдачей и баллом
 * проходит день или неделя. Всё это время ученик не знал, посмотрели его
 * работу или нет, и узнать мог только одним способом — сам вспомнить про
 * урок и открыть его вкладку. Уведомление снимает с него эту обязанность.
 *
 * Ни push, ни писем здесь нет и не будет: сайт статический, адреса ученика
 * мы не спрашиваем, а телефон в пятом классе есть не у всех. Уведомление
 * ждёт ученика на сайте и висит, пока он его не прочтёт.
 */

/**
 * Метка проверки — то, с чем сравнивается «уже видел».
 *
 * Единица вместо нуля не случайна: у работ, проверенных до появления
 * уведомлений, времени проверки в базе нет, а сказать про них надо — балл
 * ученику так и не показали. Единица больше нуля, поэтому такая работа
 * уведомит один раз и, будучи отмеченной, замолчит навсегда.
 */
export function меткаПроверки(работа) {
  return Number(работа?.checkedAt) || 1;
}

/**
 * Проверки, о которых ученику ещё не говорили.
 *
 * Сравнивается время, а не сам факт: учитель теперь может переправить балл,
 * и переправленный балл — это новость ровно так же, как первый. Время
 * проверки при этом обновляется, поэтому метка растёт и работа всплывает
 * заново.
 */
export function новыеПроверки(работы = {}, увиденное = {}) {
  const новые = [];

  for (const [lessonId, работа] of Object.entries(работы ?? {})) {
    if (!работа || работа.manualScore === undefined) continue;

    const метка = меткаПроверки(работа);
    if (Number(увиденное?.[lessonId] ?? 0) >= метка) continue;

    новые.push({
      lessonId,
      manualScore: работа.manualScore,
      comment: работа.comment ?? '',
      метка,
    });
  }

  return новые.sort((a, b) => b.метка - a.метка);
}

export function createПроверки({ api = rest, сессия = () => null, токен = async () => null } = {}) {
  /** Что нового сказал учитель. Пусто — и когда нечего сказать, и когда нет связи. */
  async function новое() {
    const s = сессия();
    if (!s?.studentId) return [];

    const token = await токен();
    if (!token) return [];

    try {
      const [работы, увиденное] = await Promise.all([
        api.dbGet(`${ROOT}/submissions/${s.studentId}`, { token }),
        api.dbGet(`${ROOT}/progress/${s.studentId}/checks`, { token }).catch(() => null),
      ]);
      return новыеПроверки(работы ?? {}, увиденное ?? {});
    } catch {
      // Нет связи или доступа — уведомление подождёт до следующего захода.
      // Ронять из-за него страницу нельзя: оно тут не главное.
      return [];
    }
  }

  /**
   * Помечает проверку прочитанной.
   *
   * Отметка живёт в базе, а не в браузере: ученик открывает сайт и с телефона,
   * и с компьютера в кабинете, а узнать про свой балл он должен один раз, а не
   * на каждом устройстве заново.
   */
  async function отметить(проверки) {
    const s = сессия();
    if (!s?.studentId || !проверки?.length) return null;

    const token = await токен();
    if (!token) return null;

    const запись = {};
    for (const п of проверки) запись[п.lessonId] = п.метка;

    try {
      await api.dbPatch(`${ROOT}/progress/${s.studentId}/checks`, запись, { token });
    } catch {
      // Не записалось — уведомление придёт ещё раз. Это лучше, чем потерять
      // его молча: повтор надоедает, пропажа обманывает.
      return null;
    }
    return запись;
  }

  return { новое, отметить };
}
