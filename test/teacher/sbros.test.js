import { test } from 'node:test';
import assert from 'node:assert/strict';
import { планСброса, чистыйПрогресс, НЕПРИКОСНОВЕННЫЕ } from '../../js/teacher/sbros.js';

const КОРЕНЬ = 'schools/apts';
const план = () => планСброса({ root: КОРЕНЬ, classId: '7a', studentIds: ['с1', 'с2'], сброс: 1000 });

/*
  Главный тест этого файла. Обнуление идёт по живой базе, где рядом с
  баллами лежат коды входа: их в базе нет вовсе, только хеши, и восстановить
  их нельзя — забытый код выдают новый. Допиши сюда `secrets` по
  невнимательности — и весь класс останется на улице.
*/
test('обнуление не трогает коды, карточки, привязки и сданные работы', () => {
  for (const запись of план()) {
    for (const ветка of НЕПРИКОСНОВЕННЫЕ) {
      assert.equal(
        запись.path.includes(`/${ветка}/`),
        false,
        `обнуление полезло в ${ветка}: ${запись.path}`,
      );
    }
  }
});

test('на каждого ученика ровно две записи — прогресс и строка таблицы', () => {
  const записи = план();
  assert.equal(записи.length, 4);
  assert.deepEqual(записи.map((з) => з.path), [
    `${КОРЕНЬ}/progress/с1/game`,
    `${КОРЕНЬ}/leaderboard/7a/с1`,
    `${КОРЕНЬ}/progress/с2/game`,
    `${КОРЕНЬ}/leaderboard/7a/с2`,
  ]);
});

test('строка таблицы снимается, а прогресс обнуляется с пометкой времени', () => {
  const записи = план();
  assert.equal(записи.find((з) => з.path.includes('/leaderboard/')).value, null);
  assert.deepEqual(записи.find((з) => з.path.includes('/progress/')).value, {
    v: 1, lessons: {}, weeks: {}, lastSeen: 0, resetAt: 1000,
  });
});

// Без пометки времени браузер ребёнка залил бы старую копию обратно,
// и обнуление продержалось бы до первого его захода.
test('пометка времени обязательна', () => {
  assert.equal(чистыйПрогресс(777).resetAt, 777);
});

test('класс без учеников не даёт ни одной записи', () => {
  assert.deepEqual(планСброса({ root: КОРЕНЬ, classId: '7a', studentIds: [], сброс: 1 }), []);
});
