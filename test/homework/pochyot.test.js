import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  процентРаботы,
  успешность,
  МАКС_ЗА_РАБОТУ,
  сданоКлассом,
  баллыЗаРаботу, домашниеБаллы, развёрнутаяЧасть, максимумРазвёрнутого, развёрнутыеЗадания,
  ПОТОЛОК_ДОМАШКИ, БОНУС_ЗА_100,
} from '../../js/homework/pochyot.js';

const ВСЁ = ПОТОЛОК_ДОМАШКИ + БОНУС_ЗА_100;

/*
  Почёт строится по этим числам, и ошибка здесь не падает, а тихо ставит
  детей не на свои места. Главное правило — кто сделал правильнее, тот выше.
*/

const работа = (поля) => ({ submittedAt: 1, ...поля });

test('всё верно — потолок и бонус сверху', () => {
  assert.equal(баллыЗаРаботу(работа({ correct: 14, total: 14 })), ВСЁ);
});

test('бонус только за сто процентов, а не за почти', () => {
  const почти = баллыЗаРаботу(работа({ correct: 13, total: 14 }));
  assert.equal(почти, 28);
  assert.ok(ВСЁ - почти > 10, 'безошибочная заметно выше почти безошибочной');
});

test('бонус ждёт проверки развёрнутого ответа', () => {
  const р = { correct: 10, total: 10, open: { o: 'ответ' }, manualMax: 3 };
  assert.equal(баллыЗаРаботу(работа(р)), ПОТОЛОК_ДОМАШКИ, 'пока не проверено — без бонуса');
  assert.equal(баллыЗаРаботу(работа({ ...р, manualScore: 3 })), ВСЁ);
  assert.equal(баллыЗаРаботу(работа({ ...р, manualScore: 2 })), 28, 'не высший балл — без бонуса');
});

test('максимум развёрнутого берётся из урока', () => {
  assert.equal(максимумРазвёрнутого({ homework: { open: [{ maxScore: 2 }] } }), 2);
  assert.equal(максимумРазвёрнутого({ homework: {} }), 3);
});

/*
  Развёрнутых заданий в уроке два места: вопрос с ключом среди вопросов
  домашки и задание без ключа в конце. До 23 сентября 2026 считалось, что
  место одно, и панель проверки показывала учителю ответ на вопрос, которого
  не знала: ни формулировки, ни ключа. Таких вопросов на сайте сорок одно.
*/
test('развёрнутые задания собираются из обоих мест урока', () => {
  const урок = {
    homework: {
      questions: [
        { id: 'q1', type: 'choice', options: ['а', 'б'], correct: 0 },
        { id: 'q2', type: 'open', text: 'Объясни, почему', answerKey: 'Потому что', maxScore: 2 },
        { id: 'q3', type: 'short', answers: ['корень'] },
      ],
      open: [{ id: 'o1', prompt: 'Разбери случай', maxScore: 3 }],
    },
  };

  assert.deepEqual(развёрнутыеЗадания(урок).map((q) => q.id), ['q2', 'o1'],
    'порядок тот же, что в бланке: сначала вопросы, потом задание в конце');
  assert.deepEqual(развёрнутыеЗадания({ homework: {} }), []);
});

/*
  Балл учитель ставит один, за всю развёрнутую часть сразу. Значит, максимум
  — это сумма: при заданиях по 3 и 2 балла работа, сделанная целиком, должна
  получать пять. До правки бралось наибольшее, и высший балл за вторую
  половину работы поставить было нечем.
*/
test('максимум развёрнутого складывается из всех заданий', () => {
  const урок = {
    homework: {
      questions: [{ id: 'q2', type: 'open', maxScore: 2 }],
      open: [{ id: 'o1', maxScore: 3 }],
    },
  };
  assert.equal(максимумРазвёрнутого(урок), 5);

  // Задание без цены не добавляет ничего, но и не обнуляет остальные.
  assert.equal(максимумРазвёрнутого({ homework: { open: [{ id: 'o1', maxScore: 3 }, { id: 'o2' }] } }), 3);
});

test('баллы растут вместе с долей верных ответов', () => {
  const слабая = баллыЗаРаботу(работа({ correct: 4, total: 14 }));
  const средняя = баллыЗаРаботу(работа({ correct: 9, total: 14 }));
  const сильная = баллыЗаРаботу(работа({ correct: 12, total: 14 }));
  assert.ok(слабая < средняя && средняя < сильная, `${слабая} < ${средняя} < ${сильная}`);
  assert.equal(баллыЗаРаботу(работа({ correct: 7, total: 14 })), 15, 'половина — половина потолка');
});

test('ни одного верного — ноль', () => {
  assert.equal(баллыЗаРаботу(работа({ correct: 0, total: 10 })), 0);
});

test('балл учителя за развёрнутый ответ входит в счёт', () => {
  const без = { correct: 10, total: 10, open: { o1: 'ответ' }, manualMax: 3 };
  assert.equal(баллыЗаРаботу(работа({ ...без, manualScore: 3 })), ВСЁ);
  assert.equal(баллыЗаРаботу(работа({ ...без, manualScore: 0 })), 23, 'десять из тринадцати');
  assert.ok(баллыЗаРаботу(работа({ ...без, manualScore: 2 })) > баллыЗаРаботу(работа({ ...без, manualScore: 1 })));
});

test('непроверенный развёрнутый ответ пока не в счёте', () => {
  const р = работа({ correct: 10, total: 10, open: { o1: 'ответ' } });
  assert.equal(развёрнутаяЧасть(р), null);
  assert.equal(баллыЗаРаботу(р), 30, 'без бонуса: ответ ещё ждёт учителя');
});

test('пустой развёрнутый ответ — сразу ноль, а не пропуск', () => {
  const р = работа({ correct: 10, total: 10, open: { o1: '   ' } });
  assert.deepEqual(развёрнутаяЧасть(р), { получено: 0, из: 3 });
  assert.ok(баллыЗаРаботу(р) < 30);
});

test('без записанного максимума берётся три, но не меньше поставленного', () => {
  assert.deepEqual(развёрнутаяЧасть(работа({ open: { o: 'а' }, manualScore: 2 })), { получено: 2, из: 3 });
  assert.deepEqual(развёрнутаяЧасть(работа({ open: { o: 'а' }, manualScore: 5 })), { получено: 5, из: 5 });
  assert.deepEqual(развёрнутаяЧасть(работа({ open: { o: 'а' }, manualScore: 1, manualMax: 2 })), { получено: 1, из: 2 });
});

test('работа из первых версий, только с процентом, считается по проценту', () => {
  assert.equal(баллыЗаРаботу(работа({ percent: 100 })), ВСЁ);
  assert.equal(баллыЗаРаботу(работа({ percent: 50 })), 15);
});

test('несданная работа не стоит ничего', () => {
  assert.equal(баллыЗаРаботу({ correct: 10, total: 10 }), 0);
  assert.equal(баллыЗаРаботу(null), 0);
});

test('за неделю идут только работы, сданные на этой неделе', () => {
  const СЕЙЧАС = new Date(2026, 8, 16);
  const счёт = домашниеБаллы({
    u1: { submittedAt: new Date(2026, 8, 14).getTime(), correct: 10, total: 10 },
    u2: { submittedAt: new Date(2026, 8, 9).getTime(), correct: 5, total: 10 },
  }, СЕЙЧАС);
  assert.deepEqual(счёт, { hwXp: 55, hwWeekXp: 40, hwDone: 2, hwWeekDone: 1 });
});

/*
  Шкала класса — сданные домашние работы из заданных (решение учителя от
  17 сентября 2026). До этого сверху стояли уроки, пройденные в тренажёре,
  а снизу — заданные домашки, и у 8 класса выходило «1 из 95».
*/
test('класс сдал столько работ, сколько сдали его ученики', () => {
  const шкала = сданоКлассом([{ hwDone: 2 }, { hwDone: 1 }, {}], { u1: {}, u2: {} });
  assert.deepEqual(шкала, { сдано: 3, задано: 6, процент: 50 });
});

// Убранный урок из заданий не исчезает: сданное по нему осталось в журнале.
test('убранное задание остаётся в счёте заданного', () => {
  assert.equal(сданоКлассом([{ hwDone: 1 }], { u1: { isOpen: false } }).задано, 1);
});

// Ученик мог перейти из другого класса со своими работами: больше ста
// процентов шкала показывать не должна.
test('сданных не бывает больше заданных', () => {
  assert.deepEqual(сданоКлассом([{ hwDone: 5 }], { u1: {} }), { сдано: 1, задано: 1, процент: 100 });
});

test('без заданий шкала нулевая и не делит на ноль', () => {
  assert.deepEqual(сданоКлассом([{ hwDone: 2 }], {}), { сдано: 0, задано: 0, процент: 0 });
  assert.deepEqual(сданоКлассом(), { сдано: 0, задано: 0, процент: 0 });
});

test('испорченное число в строке считается нулём', () => {
  assert.equal(сданоКлассом([{ hwDone: 'много' }, { hwDone: 1 }], { u1: {} }).сдано, 1);
});

/*
  Успешность — средний процент за одну работу. Нужна школьному почёту:
  классам задают разное число работ, и сумма сравнивает не качество, а
  количество заданного (решение учителя от 17 сентября 2026).
*/
test('успешность — средняя доля от максимума одной работы', () => {
  assert.equal(МАКС_ЗА_РАБОТУ, 40);
  assert.equal(успешность(80, 2), 100);
  assert.equal(успешность(60, 2), 75);
  assert.equal(успешность(35, 1), 88);
});

test('успешности без сданных работ нет', () => {
  assert.equal(успешность(0, 0), null);
  assert.equal(успешность(30, undefined), null);
  assert.equal(успешность('много', 1), null);
});

test('успешность не выходит за сто процентов', () => {
  assert.equal(успешность(999, 1), 100);
});

/*
  Процент за работу в журнале и у ученика — тем же счётом, что в почёте
  (решение учителя от 17 сентября 2026). До этого там стоял процент при
  сдаче, только по автопроверке: работа с нулём за развёрнутый ответ
  стояла в журнале на ста процентах.
*/
const сдана = { submittedAt: 1, correct: 10, total: 10, open: { o: 'ответ' }, manualMax: 3 };

test('ноль за развёрнутый ответ опускает процент работы', () => {
  assert.deepEqual(процентРаботы({ ...сдана, manualScore: 0 }).процент, 77);
});

test('балл учителя входит в процент работы', () => {
  assert.equal(процентРаботы({ ...сдана, manualScore: 2 }).процент, 92);
  assert.equal(процентРаботы({ ...сдана, manualScore: 3 }).процент, 100);
});

test('пока ответ не проверен, процент по автопроверке и помечен', () => {
  const итог = процентРаботы(сдана);
  assert.equal(итог.процент, 100);
  assert.equal(итог.ждёт, true);
});

test('пустой развёрнутый ответ сразу считается нулём', () => {
  const итог = процентРаботы({ ...сдана, open: { o: '   ' } });
  assert.equal(итог.процент, 77);
  assert.equal(итог.ждёт, false);
});

test('работа без развёрнутого ответа — по автопроверке, без пометки', () => {
  const итог = процентРаботы({ submittedAt: 1, correct: 7, total: 10 });
  assert.equal(итог.процент, 70);
  assert.equal(итог.ждёт, false);
});

test('старая работа с одним процентом показывает его же', () => {
  assert.equal(процентРаботы({ submittedAt: 1, percent: 85 }).процент, 85);
});

test('несданной работе процента нет', () => {
  assert.equal(процентРаботы(null), null);
  assert.equal(процентРаботы({ correct: 1, total: 1 }), null);
});
