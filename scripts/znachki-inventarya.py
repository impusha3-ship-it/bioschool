# -*- coding: utf-8 -*-
"""
Рисует значки инвентаря для этапа «собери стол» в лабораторной работе.

Почему рисуем, а не берём готовое. Поиск по открытым библиотекам разобран в
`docs/plans/2026-09-06-znachki-inventarya.md`. Коротко: годного набора нет.
DBCLS и NIH BioArt — наборы для исследовательской лаборатории, и школьного
инвентаря там почти нет: спиртовки, лупы, скальпеля и склянки не нашлось
вовсе. Из четырёх найденных при разборе построчно осталось два спорных:
у DBCLS «needle» — это тонкая игла без рукоятки, а препаровальная игла
рукояткой и опознаётся; их пипетка нарисована обводкой по диагонали и рядом
с нашими прямыми значками встаёт криво. Два файла NIH BioArt плоские и
хорошие, но сделаны в Illustrator через clip-path, и сведение их к нашим трём
ступеням светлоты — работа не меньшая, чем нарисовать.

Язык набора задан теми пятью значками, что уже нарезаны из схемы «Что стоит
на столе в кабинете»: примитивы, плоские заливки в три ступени, обводка
приходит из темы. Стакан — два пути, пробирка — один. Новые сделаны так же,
и потому садятся в один ряд со старыми.

Цвет не зашит: классы `d-eq-light` (бумага), `d-eq-mid` (заливка потемнее),
`d-eq-accent` (жидкость и пламя), `d-eq-none` (только обводка). Толщина
обводки не зависит от viewBox — за это отвечает `vector-effect` в base.css,
поэтому холст у каждого значка свой, по размеру предмета.

    python scripts/znachki-inventarya.py
"""
import io
import os

ВЫХОД = 'img/bio'

ШАПКА = (
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    '<!--\n'
    '  {название} — значок инвентаря для сбора стола в лабораторной работе.\n'
    '  Нарисован scripts/znachki-inventarya.py в том же языке, что нарезанные\n'
    '  из схемы приборы: примитивы, три ступени светлоты, обводка из темы.\n'
    '  Цвета не зашиты — приходят по классам d-eq-*.\n'
    '-->\n'
)

# name → (holst, название, тело)
ЗНАЧКИ = {}


def значок(файл, название, viewbox, тело):
    ЗНАЧКИ[файл] = (viewbox, название, тело.strip())


# ── Стекло ───────────────────────────────────────────────────────────────
# Предметное стекло: длинная тонкая пластинка, посередине мазок препарата.
значок('inv-predmetnoe-steklo.svg', 'Предметное стекло', '0 0 96 96', """
  <g transform="rotate(-32 48 48)">
    <rect class="d-eq-light" x="0" y="34" width="96" height="28" rx="3"/>
    <ellipse class="d-eq-accent" cx="48" cy="48" rx="16" ry="9"/>
  </g>
""")

# Покровное стекло: маленький квадратик. От предметного его отличает только
# форма, и это верно: в жизни тоже отличает.
значок('inv-pokrovnoe-steklo.svg', 'Покровное стекло', '0 0 48 48', """
  <rect class="d-eq-light" x="5" y="5" width="38" height="38" rx="2"/>
  <path class="d-eq-none" d="M11 17 17 11M11 27 27 11"/>
""")

# ── Держат и режут ───────────────────────────────────────────────────────
# Пинцет: две сходящиеся кверху пружинящие ветви.
значок('inv-pincet.svg', 'Пинцет', '0 0 52 112', """
  <path class="d-eq-mid" d="M20 8h12l-2 12H22z"/>
  <path class="d-eq-light" d="M22 20h5l-2 46-4 40-3-40z"/>
  <path class="d-eq-light" d="M27 20h5l6 46-3 40-6-40z"/>
""")

# Препаровальная игла: рукоятка и тонкое острие. Рукоятка и есть то, по чему
# её узнают, — без неё это просто игла.
значок('inv-igla.svg', 'Препаровальная игла', '0 0 30 124', """
  <rect class="d-eq-mid" x="5" y="6" width="20" height="46" rx="9"/>
  <path class="d-eq-none" d="M5 18h20M5 28h20M5 38h20"/>
  <path class="d-eq-mid" d="M11 52h8v8h-8z"/>
  <path class="d-eq-light" d="M14 60h2l-1 58z"/>
""")

# Скальпель: рукоять и лезвие со скосом.
значок('inv-skalpel.svg', 'Скальпель', '0 0 48 120', """
  <rect class="d-eq-mid" x="15" y="52" width="16" height="62" rx="5"/>
  <path class="d-eq-light" d="M23 6c12 12 17 26 17 38v10H8V44c0-12 3-26 15-38z"/>
  <path class="d-eq-none" d="M8 44h32"/>
""")

# ── Смотрят и меряют ─────────────────────────────────────────────────────
# Ручная лупа: линза, оправа и ручка.
значок('inv-lupa.svg', 'Ручная лупа', '0 0 68 112', """
  <rect class="d-eq-mid" x="28" y="62" width="12" height="46" rx="5"/>
  <circle class="d-eq-mid" cx="34" cy="38" r="32"/>
  <circle class="d-eq-light" cx="34" cy="38" r="25"/>
""")

# Линейка: пластинка с делениями. Деления рисуются обводкой, а не заливкой.
значок('inv-lineyka.svg', 'Линейка', '0 0 28 124', """
  <rect class="d-eq-light" x="5" y="5" width="18" height="114" rx="2"/>
  <path class="d-eq-none" d="M5 21h9M5 37h6M5 53h9M5 69h6M5 85h9M5 101h6"/>
""")

# ── Наливают и капают ────────────────────────────────────────────────────
# Пипетка: стеклянная трубка с резиновой грушей — та самая школьная.
значок('inv-pipetka.svg', 'Пипетка', '0 0 34 124', """
  <path class="d-eq-accent" d="M8 6h18v26H8z"/>
  <path class="d-eq-light" d="M11 32h12v58l-6 28-6-28z"/>
  <path class="d-eq-none" d="M8 20h18"/>
""")

# Склянки в наборе нет намеренно. Растворы опознают по подписи, а не по
# форме пузырька: в работе про свойства организмов на одной полке стоят и
# раствор йода, и растительное масло — два одинаковых значка не различить
# никак. Вещества идут подписанными плашками, см. «без картинки» в реестре.

# Спиртовка: корпус, горловина, фитиль и пламя.
значок('inv-spirtovka.svg', 'Спиртовка', '0 0 76 116', """
  <path class="d-eq-accent" d="M38 6c9 10 13 18 13 25a13 13 0 0 1-26 0c0-7 4-15 13-25z"/>
  <rect class="d-eq-mid" x="33" y="44" width="10" height="12"/>
  <path class="d-eq-light" d="M22 56h32c8 0 14 8 14 20v25a5 5 0 0 1-5 5H13a5 5 0 0 1-5-5V76c0-12 6-20 14-20z"/>
  <path class="d-eq-none" d="M8 84h60"/>
""")

# ── Штатив ───────────────────────────────────────────────────────────────
# Штатив для пробирок: подставка с гнёздами и стойка с кольцами.
значок('inv-shtativ.svg', 'Штатив для пробирок', '0 0 116 92', """
  <rect class="d-eq-mid" x="6" y="62" width="104" height="24" rx="4"/>
  <path class="d-eq-light" d="M20 6h18v50a9 9 0 0 1-18 0z"/>
  <path class="d-eq-light" d="M49 6h18v50a9 9 0 0 1-18 0z"/>
  <path class="d-eq-light" d="M78 6h18v50a9 9 0 0 1-18 0z"/>
  <path class="d-eq-none" d="M6 70h104"/>
""")

# ── Расходное ────────────────────────────────────────────────────────────
# Маркер: корпус, колпачок и пишущий конец.
значок('inv-marker.svg', 'Маркер', '0 0 32 118', """
  <rect class="d-eq-accent" x="6" y="6" width="20" height="34" rx="4"/>
  <rect class="d-eq-light" x="7" y="40" width="18" height="58"/>
  <path class="d-eq-mid" d="M11 98h10l-5 14z"/>
""")

# Лист белой бумаги: на него вытряхивают спо́ры. Загнутый угол отличает лист
# от предметного стекла, которое тоже прямоугольник.
значок('inv-bumaga.svg', 'Лист белой бумаги', '0 0 84 108', """
  <path class="d-eq-light" d="M6 6h52l20 20v76H6z"/>
  <path class="d-eq-mid" d="M58 6v20h20z"/>
""")

# Полиэтиленовый пакет: им накрывают побег в опыте на испарение.
значок('inv-paket.svg', 'Полиэтиленовый пакет', '0 0 84 108', """
  <path class="d-eq-none" d="M28 30V16a14 10 0 0 1 28 0v14"/>
  <path class="d-eq-light" d="M10 30h64l-6 72H16z"/>
  <path class="d-eq-none" d="M42 40v54"/>
""")


for файл, (viewbox, название, тело) in ЗНАЧКИ.items():
    svg = (
        ШАПКА.format(название=название)
        + f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" '
        + f'role="img" aria-label="{название}">\n{тело}\n</svg>\n'
    )
    io.open(os.path.join(ВЫХОД, файл), 'w', encoding='utf-8', newline='\n').write(svg)
    print(f'  {файл}  ({название})')

print(f'нарисовано: {len(ЗНАЧКИ)}')
