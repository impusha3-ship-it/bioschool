import { test } from 'node:test';
import assert from 'node:assert/strict';
import { домашниеБаллы } from '../../scripts/pereschet-pochyota.mjs';

/*
  Разовый пересчёт пишет числа прямо в живую таблицу почёта, и посчитать их
  он должен ровно так же, как считает сайт. Ошибка здесь не падает, а тихо
  ставит детям чужие места, поэтому проверяется и цена работы, и граница
  недели.
*/

const СЕЙЧАС = new Date(2026, 8, 16); // среда 38-й недели
const вПонедельник = new Date(2026, 8, 14).getTime();
const наПрошлойНеделе = new Date(2026, 8, 9).getTime();

test('работа на девяносто и выше стоит дороже', () => {
  const счёт = домашниеБаллы({
    u1: { submittedAt: наПрошлойНеделе, percent: 100 },
    u2: { submittedAt: наПрошлойНеделе, percent: 89 },
  }, СЕЙЧАС);

  assert.equal(счёт.hwXp, 50, 'тридцать за отличную и двадцать за остальную');
});

test('в недельный счёт идут только работы этой недели', () => {
  const счёт = домашниеБаллы({
    u1: { submittedAt: вПонедельник, percent: 100 },
    u2: { submittedAt: наПрошлойНеделе, percent: 100 },
  }, СЕЙЧАС);

  assert.equal(счёт.hwXp, 60);
  assert.equal(счёт.hwWeekXp, 30, 'прошлая неделя в эту не идёт');
});

// Балл за развёрнутый ответ ставит учитель, и в баллы прогресса он не входит
// ни на сайте, ни здесь: percent считается по автопроверке.
test('непроверенная работа считается наравне с проверенной', () => {
  const счёт = домашниеБаллы({
    u1: { submittedAt: вПонедельник, percent: 100, open: { o: 'ждёт' } },
  }, СЕЙЧАС);

  assert.equal(счёт.hwXp, 30);
});

test('у того, кто ничего не сдавал, ноль, а не пустота', () => {
  assert.deepEqual(домашниеБаллы(undefined, СЕЙЧАС), { hwXp: 0, hwWeekXp: 0 });
  assert.deepEqual(домашниеБаллы({}, СЕЙЧАС), { hwXp: 0, hwWeekXp: 0 });
});

// Работа без времени сдачи — испорченная запись; посчитать её в неделю
// нельзя, а молча дать за неё баллы значило бы наградить за поломку.
test('запись без времени сдачи пропускается', () => {
  assert.deepEqual(домашниеБаллы({ u1: { percent: 100 } }, СЕЙЧАС), { hwXp: 0, hwWeekXp: 0 });
});

test('работа без процента даёт обычную цену, а не ноль', () => {
  assert.equal(домашниеБаллы({ u1: { submittedAt: вПонедельник } }, СЕЙЧАС).hwXp, 20);
});
