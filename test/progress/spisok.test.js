import { test } from 'node:test';
import assert from 'node:assert/strict';
import { прогрессРаздела, прогрессКурса } from '../../js/pages/class.js';

const РАЗДЕЛ = {
  id: 'nauka',
  title: 'Наука',
  lessons: [{ id: 'у1' }, { id: 'у2' }, { id: 'у3' }, { id: 'у4' }],
};

const КУРС = {
  sections: [
    РАЗДЕЛ,
    { id: 'kletka', title: 'Клетка', lessons: [{ id: 'у5' }, { id: 'у6' }] },
  ],
};

test('в разделе считаются только пройденные уроки', () => {
  const состояние = { lessons: { у1: { done: true }, у2: { game0: 10 }, у3: { done: true } } };
  const п = прогрессРаздела(РАЗДЕЛ, состояние);
  assert.equal(п.пройдено, 2, 'начатый урок пройденным не считается');
  assert.equal(п.всего, 4);
  assert.equal(п.процент, 50);
});

test('пустое состояние даёт ноль, а не ошибку', () => {
  const п = прогрессРаздела(РАЗДЕЛ, {});
  assert.deepEqual([п.пройдено, п.всего, п.процент], [0, 4, 0]);
});

// Раздел без уроков бывает: программа расписана вперёд, уроки ещё пишутся.
// Делить на ноль здесь нельзя — на экран пошло бы NaN.
test('раздел без уроков не роняет счёт', () => {
  const п = прогрессРаздела({ id: 'x', title: 'X', lessons: [] }, {});
  assert.deepEqual([п.пройдено, п.всего, п.процент], [0, 0, 0]);
});

test('по курсу складываются все разделы', () => {
  const состояние = { lessons: { у1: { done: true }, у5: { done: true }, у6: { done: true } } };
  const п = прогрессКурса(КУРС, состояние);
  assert.equal(п.пройдено, 3);
  assert.equal(п.всего, 6);
  assert.equal(п.процент, 50);
});

// Уроки чужого класса лежат в том же состоянии: у пятиклассника, открывшего
// седьмой класс, счёт не должен раздуваться его собственными уроками.
test('чужие уроки в счёт курса не идут', () => {
  const состояние = { lessons: { у1: { done: true }, 'из-другого-класса': { done: true } } };
  assert.equal(прогрессКурса(КУРС, состояние).пройдено, 1);
});
