import { test } from 'node:test';
import assert from 'node:assert/strict';
import { домашниеБаллы } from '../../scripts/pereschet-pochyota.mjs';
import { домашниеБаллы as вБраузере } from '../../js/homework/pochyot.js';

/*
  Скрипт пересчёта пишет числа прямо в живую таблицу почёта, и посчитать их
  он должен ровно так же, как считают сайт и панель учителя. Само правило
  проверяется в test/homework/pochyot.test.js; здесь — что скрипт им и
  пользуется, а не держит свою копию.
*/

test('скрипт считает тем же правилом, что и сайт', () => {
  assert.equal(домашниеБаллы, вБраузере);
});

// Работа без времени сдачи — испорченная запись; посчитать её в неделю
// нельзя, а молча дать за неё баллы значило бы наградить за поломку.
test('запись без времени сдачи пропускается', () => {
  assert.deepEqual(домашниеБаллы({ u1: { percent: 100 } }, new Date(2026, 8, 16)), { hwXp: 0, hwWeekXp: 0, hwDone: 0 });
});

test('у того, кто ничего не сдавал, ноль, а не пустота', () => {
  assert.deepEqual(домашниеБаллы(undefined, new Date(2026, 8, 16)), { hwXp: 0, hwWeekXp: 0, hwDone: 0 });
});
