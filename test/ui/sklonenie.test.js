import { test } from 'node:test';
import assert from 'node:assert/strict';
import { баллов, недель, уроков } from '../../js/ui/sklonenie.js';

test('единица и всё, что на неё кончается', () => {
  assert.equal(баллов(1), 'балл');
  assert.equal(баллов(21), 'балл');
  assert.equal(баллов(101), 'балл');
});

test('от двух до четырёх', () => {
  assert.equal(баллов(2), 'балла');
  assert.equal(баллов(34), 'балла');
  assert.equal(баллов(164), 'балла');
});

// Ловушка русского счёта: 11–14 идут во множественном, хотя кончаются на
// 1–4. Именно на ней и споткнулось «164 баллов» в разборе.
test('одиннадцать–четырнадцать — исключение', () => {
  for (const n of [11, 12, 13, 14, 111, 112, 213, 314]) {
    assert.equal(баллов(n), 'баллов', `${n}`);
  }
});

test('ноль и пять с лишним', () => {
  assert.equal(баллов(0), 'баллов');
  assert.equal(баллов(5), 'баллов');
  assert.equal(баллов(100), 'баллов');
});

test('те же правила у недель и уроков', () => {
  assert.deepEqual([недель(1), недель(3), недель(11)], ['неделю', 'недели', 'недель']);
  assert.deepEqual([уроков(1), уроков(3), уроков(11)], ['урок', 'урока', 'уроков']);
});
