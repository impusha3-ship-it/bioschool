import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { поправка, УРОК, ВОПРОС, СТАРЫЙ_КЛЮЧ } from '../../scripts/popravka-zon-kornya.mjs';

/*
  В ключе задания про зоны корня стояло 2431 — последней шла зона всасывания
  вместо зоны проведения (нашёл учитель 19 октября 2026). Работы, сданные до
  исправления, проверялись старым ключом, и поправка возвращает балл тем, у
  кого ответ был верным. У ответивших по старому ключу балл не отнимается:
  они отвечали по тому, что показывал сайт.
*/

const КОРЕНЬ = fileURLToPath(new URL('../..', import.meta.url));
const новые = ['2413', '2 4 1 3', '2,4,1,3'];
const работа = (ответ, доп = {}) => ({
  submittedAt: 1, correct: 12, total: 16, percent: 75,
  answers: { [ВОПРОС]: ответ }, ...доп,
});

test('верный порядок зон — от кончика, с проведением последней', async () => {
  const урок = JSON.parse(await readFile(join(КОРЕНЬ, 'content', 'lessons', `${УРОК}.json`), 'utf8'));
  const вопрос = урок.homework.questions.find((q) => q.id === ВОПРОС);

  assert.ok(вопрос.answers.includes('2413'), 'в ключе должно стоять 2413');
  assert.equal(вопрос.answers.some((о) => СТАРЫЙ_КЛЮЧ.includes(о)), false, 'старого ключа в задании быть не должно');
  // Порядок в самом задании: 1) всасывания 2) деления 3) проведения 4) растяжения.
  assert.match(вопрос.text, /1\) зона всасывания[\s\S]*2\) зона деления[\s\S]*3\) зона проведения[\s\S]*4\) зона растяжения/);
});

test('ответившему верно балл возвращается', () => {
  assert.deepEqual(поправка(работа('2413'), { новые }), { correct: 13, percent: 81, zonyFix: 1 });
});

test('запись засчитывается в любом виде, как и на сайте', () => {
  assert.deepEqual(поправка(работа(' 2 4 1 3 '), { новые }), { correct: 13, percent: 81, zonyFix: 1 });
  assert.deepEqual(поправка(работа('2,4,1,3'), { новые }), { correct: 13, percent: 81, zonyFix: 1 });
});

test('ответившему по старому ключу балл не отнимается', () => {
  assert.equal(поправка(работа('2431'), { новые }), null);
});

test('ответившему мимо обоих ключей ничего не меняется', () => {
  assert.equal(поправка(работа('1234'), { новые }), null);
  assert.equal(поправка(работа(''), { новые }), null);
  assert.equal(поправка({ submittedAt: 1, correct: 1, total: 2 }, { новые }), null);
});

// Работа из первых версий сайта может не нести ни correct, ни total: прибавить
// к пустоте нечего, и выдумывать число нельзя.
test('без счёта верных и всего работа не трогается', () => {
  assert.equal(поправка({ submittedAt: 1, percent: 80, answers: { [ВОПРОС]: '2413' } }, { новые }), null);
});

test('выше потолка работа не поднимается', () => {
  assert.equal(поправка(работа('2413', { correct: 16, total: 16, percent: 100 }), { новые }), null);
});

// Второй запуск не должен прибавить балл ещё раз: поправленная работа
// помечена, и скрипт её пропускает.
test('поправленная работа второй раз не трогается', () => {
  assert.equal(поправка(работа('2413', { zonyFix: 1 }), { новые }), null);
});
