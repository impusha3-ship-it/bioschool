import { неделя } from '../progress/weeks.js';
import { НОРМЫ } from '../progress/core.js';

/**
 * Сколько сданная домашняя работа даёт в таблицу почёта.
 *
 * Решение учителя от 16 сентября 2026: выше в почёте должен быть тот, кто
 * делает правильнее, а не тот, кто просто сдал. До этого любая работа
 * стоила двадцать баллов и ещё десять при девяноста процентах — работа на
 * тридцать процентов и работа на восемьдесят пять весили одинаково, а балл
 * учителя за развёрнутый ответ не весил ничего.
 *
 * Теперь работа стоит долю от потолка, и доля — это всё набранное из всего
 * возможного: каждый верный ответ в игре и в вопросах — одно очко, балл
 * учителя за развёрнутый ответ — столько очков, сколько он поставил, из
 * своего максимума. Пока учитель ответ не проверил, работа считается по
 * автопроверке, а после проверки число уточняется — в любую сторону.
 *
 * Считается только из сданной работы, и так считают и браузер ученика, и
 * панель учителя: другой правды, с которой можно разойтись, нет.
 */

/** Потолок работы — прежний, чтобы почёт не менял масштаб. */
export const ПОТОЛОК_ДОМАШКИ = НОРМЫ.домашка.за + НОРМЫ.домашка.отлично;

/**
 * Бонус за работу без единой потери — решение учителя от 16 сентября 2026.
 * Сверху потолка, чтобы безошибочная работа отличалась от почти
 * безошибочной не на один балл. Развёрнутый ответ должен быть проверен и
 * оценён высшим баллом: пока учитель его не читал, бонус ждёт.
 */
export const БОНУС_ЗА_100 = 10;

/** Максимум развёрнутого ответа, если он не записан: столько у большинства уроков. */
export const МАКС_РАЗВЁРНУТОГО = 3;

/**
 * Максимум развёрнутого ответа урока — столько же кнопок видит учитель при
 * проверке. У урока без развёрнутого задания — три, как в панели.
 */
export function максимумРазвёрнутого(урок) {
  const открытые = урок?.homework?.open ?? [];
  return Math.max(...открытые.map((q) => Number(q.maxScore) || 0), 0) || МАКС_РАЗВЁРНУТОГО;
}

/**
 * Развёрнутая часть работы: сколько получено и из скольких. `null` — не в
 * счёт: развёрнутого ответа нет или учитель его ещё не читал.
 *
 * Пустой ответ считается нулём сразу: проверять учителю там нечего, и
 * оставить поле пустым не должно быть выгоднее, чем ответить плохо.
 */
export function развёрнутаяЧасть(работа) {
  const ответы = Object.values(работа?.open ?? {});
  if (!ответы.length) return null;

  const из = Number(работа.manualMax) > 0
    ? Number(работа.manualMax)
    : Math.max(МАКС_РАЗВЁРНУТОГО, Number(работа.manualScore) || 0);

  if (работа.manualScore !== undefined && работа.manualScore !== null) {
    return { получено: Math.min(Math.max(Number(работа.manualScore) || 0, 0), из), из };
  }

  const написано = ответы.some((текст) => String(текст ?? '').trim());
  return написано ? null : { получено: 0, из };
}

/**
 * Автопроверяемая часть. У работ из первых версий сайта может не быть
 * `correct` и `total`, только процент, — тогда процент идёт как десять очков.
 */
function автоЧасть(работа) {
  const total = Number(работа?.total);
  if (total > 0) return { получено: Math.min(Number(работа.correct) || 0, total), из: total };
  if (Number.isFinite(Number(работа?.percent)) && работа.percent !== undefined) {
    return { получено: Number(работа.percent) / 10, из: 10 };
  }
  return { получено: 0, из: 0 };
}

export function баллыЗаРаботу(работа) {
  if (!работа?.submittedAt) return 0;
  const авто = автоЧасть(работа);
  const развёрнутая = развёрнутаяЧасть(работа);
  const получено = авто.получено + (развёрнутая?.получено ?? 0);
  const из = авто.из + (развёрнутая?.из ?? 0);
  if (!из) return 0;
  return Math.round((ПОТОЛОК_ДОМАШКИ * получено) / из) + (безПотерь(работа, развёрнутая, получено, из) ? БОНУС_ЗА_100 : 0);
}

/** Всё набрано, и ничего не ждёт проверки. */
function безПотерь(работа, развёрнутая, получено, из) {
  if (получено < из) return false;
  const ждёт = развёрнутая === null && Object.keys(работа.open ?? {}).length > 0;
  return !ждёт;
}

/**
 * Домашние баллы ученика: за всё время и за текущую неделю.
 *
 * Неделя берётся по времени сдачи, а не по времени подсчёта: работа, сданная
 * в понедельник, должна попасть в эту неделю, даже если считали в пятницу.
 */
export function домашниеБаллы(работы = {}, сейчас = new Date()) {
  const текущая = неделя(сейчас);
  let всего = 0;
  let заНеделю = 0;
  let сдано = 0;
  let сданоЗаНеделю = 0;

  for (const работа of Object.values(работы ?? {})) {
    if (!работа?.submittedAt) continue;
    const баллы = баллыЗаРаботу(работа);
    всего += баллы;
    сдано += 1;
    if (неделя(new Date(работа.submittedAt)) === текущая) {
      заНеделю += баллы;
      сданоЗаНеделю += 1;
    }
  }

  // `hwDone` — сколько работ сдано: из него складывается «сдано классом» и
  // средняя успешность в школьном почёте; `hwWeekDone` — то же за неделю.
  return { hwXp: всего, hwWeekXp: заНеделю, hwDone: сдано, hwWeekDone: сданоЗаНеделю };
}

/** Больше этого одна работа не стоит: потолок и бонус за безошибочность. */
export const МАКС_ЗА_РАБОТУ = ПОТОЛОК_ДОМАШКИ + БОНУС_ЗА_100;

/**
 * Успешность — сколько набрано из максимума за `работ` работ, в процентах.
 * `null` — считать не из чего. Школьный почёт передаёт сюда число
 * заданных, а не сданных работ: несданная работа — ноль.
 *
 * Для школьного почёта, где рядом стоят разные классы. Решение учителя от
 * 17 сентября 2026: классам задают разное число работ (пятому — две,
 * восьмому — пять), и по сумме баллов школьную тройку занимал тот класс,
 * которому задали больше, а не тот, кто лучше сделал. Внутри класса всем
 * задано одно и то же, и там остаётся сумма.
 */
export function успешность(баллы, работ) {
  const n = Number(работ);
  if (!(n > 0) || !Number.isFinite(Number(баллы))) return null;
  return Math.min(100, Math.round((Number(баллы) / n / МАКС_ЗА_РАБОТУ) * 100));
}

/**
 * Сколько домашних работ сдал класс из заданных.
 *
 * Решение учителя от 17 сентября 2026. До этого шкала «Класс прошёл N из M»
 * делила одно на другое: сверху — уроки, до конца пройденные в тренажёре
 * (любого класса, заданные или нет), снизу — ученики, помноженные на
 * заданные уроки. У 8 класса выходило «1 из 95», хотя домашку сдавали
 * четырнадцать человек.
 *
 * Теперь и сверху, и снизу — домашние работы. Задано — ученики класса на
 * заданные уроки, включая убранные: сданное по ним в журнале осталось.
 * Сдано — сумма `hwDone` из строк учеников. Сдать можно только заданное
 * своему классу, это держат правила базы, поэтому пересекать со списком
 * заданий не нужно; сверху число всё равно ограничено — ученик мог перейти
 * из другого класса со своими работами.
 */
export function сданоКлассом(строки = [], назначения = {}) {
  const задано = строки.length * Object.keys(назначения ?? {}).length;
  const сдано = строки.reduce((n, с) => n + (Number.isFinite(с?.hwDone) ? с.hwDone : 0), 0);
  return {
    сдано: Math.min(сдано, задано),
    задано,
    процент: задано ? Math.round((Math.min(сдано, задано) / задано) * 100) : 0,
  };
}
