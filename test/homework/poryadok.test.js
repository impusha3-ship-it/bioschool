import { test } from 'node:test';
import assert from 'node:assert/strict';
import { перевестиОтветы, нуженПеревод, ТЕКУЩИЙ_ПОРЯДОК } from '../../js/homework/poryadok.js';

/*
  Ответ в работе хранится номером варианта. Переставили варианты — и номер в
  старой работе указывает на чужой вариант: разбор скажет ребёнку, что он
  выбрал то, чего не выбирал. Проверяется, что старая работа читается в новом
  порядке, а новая не переводится повторно.
*/

// Вариант с места i переехал на место куда[i]: 0→2, 1→0, 2→3, 3→1.
const таблица = { 2: { урок: { q1: [2, 0, 3, 1], q2: [1, 0, 2] } } };

test('номер старого ответа переводится на новое место того же варианта', () => {
  const ответы = перевестиОтветы({ answers: { q1: 0 } }, 'урок', таблица);
  assert.equal(ответы.q1, 2);
});

test('несколько отмеченных переводятся все', () => {
  const ответы = перевестиОтветы({ answers: { q2: [0, 2] } }, 'урок', таблица);
  assert.deepEqual(ответы.q2, [1, 2]);
});

test('вопросы не из таблицы и пустые ответы не трогаются', () => {
  const ответы = перевестиОтветы({ answers: { q1: null, q9: 3, q10: 'слово' } }, 'урок', таблица);
  assert.deepEqual(ответы, { q1: null, q9: 3, q10: 'слово' });
});

test('работа другого урока не переводится', () => {
  assert.deepEqual(перевестиОтветы({ answers: { q1: 0 } }, 'другой', таблица), { q1: 0 });
});

// Самое опасное — перевести дважды: номер снова уедет, и разбор соврёт.
test('работа, сданная при новом порядке, не переводится', () => {
  const работа = { answers: { q1: 0 }, optionsVersion: ТЕКУЩИЙ_ПОРЯДОК };
  assert.equal(нуженПеревод(работа), false);
  assert.deepEqual(перевестиОтветы(работа, 'урок', таблица), { q1: 0 });
});

test('работа без номера порядка сдана при первом и требует перевода', () => {
  assert.equal(нуженПеревод({ answers: {} }), true);
});

test('исходная работа при переводе не меняется', () => {
  const работа = { answers: { q1: 0 } };
  перевестиОтветы(работа, 'урок', таблица);
  assert.deepEqual(работа.answers, { q1: 0 });
});
