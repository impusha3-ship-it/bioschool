import { test } from 'node:test';
import assert from 'node:assert/strict';
import { собратьТабло } from '../../js/pages/tablo.js';

const НЕДЕЛЯ = '2026-W36';

const ДАННЫЕ = {
  classes: { '7a': { title: '7А', grade: 7 }, '5b': { title: '5Б', grade: 5 } },
  students: {
    s1: { name: 'Алёшин Юрий', classId: '7a' },
    s2: { name: 'Баранец София', classId: '7a' },
    s3: { name: 'Губин Илья', classId: '7a' },
    s4: { name: 'Заец Алиса', classId: '5b' },
  },
  /*
    В строке два счёта: `xp` — весь прогресс ученика, по нему учитель видит
    ступень; `hwXp` — только сданные домашние работы. Почёт строится по
    второму, и цифры здесь нарочно разные: перепутай их код — и тест увидит.
  */
  leaderboard: {
    '7a': {
      s1: { xp: 900, hwXp: 300, weekId: НЕДЕЛЯ, weekXp: 200, hwWeekXp: 40, lessonsDone: 4, hwDone: 2 },
      s2: { xp: 200, hwXp: 120, weekId: НЕДЕЛЯ, weekXp: 100, hwWeekXp: 90, lessonsDone: 2, hwDone: 1 },
      s3: { xp: 800, hwXp: 500, weekId: '2026-W35', weekXp: 90, hwWeekXp: 70, lessonsDone: 6, hwDone: 2 },
    },
    '5b': { s4: { xp: 250, hwXp: 200, weekId: НЕДЕЛЯ, weekXp: 80, hwWeekXp: 60, lessonsDone: 3, hwDone: 1 } },
  },
  assignments: { '7a': { u1: {}, u2: {} }, '5b': { u1: {} } },
};

const собрать = (данные = ДАННЫЕ) => собратьТабло({ ...данные, неделя: НЕДЕЛЯ });

test('лучшие за всё время считаются по всей школе, а не по классу', () => {
  const { всегда } = собрать().школа;
  assert.deepEqual(всегда.map((с) => с.имя), ['Губин Илья', 'Алёшин Юрий', 'Заец Алиса']);
  assert.equal(всегда[0].класс, '7А', 'рядом с именем должен стоять класс');
});

/*
  Тройка — это и есть таблица почёта: чем длиннее список, тем дешевле в нём
  место. Четвёртый по школе в неё не попадает, хотя баллы у него есть.
*/
test('общая тройка не растягивается на всех, у кого есть баллы', () => {
  const { всегда } = собрать().школа;
  assert.equal(всегда.length, 3);
  assert.equal(всегда.some((с) => с.имя === 'Баранец София'), false, 'четвёртая по школе');
});

test('тройка класса берётся из своих и считается за всё время', () => {
  const седьмой = собрать().классы.find((к) => к.id === '7a');
  assert.deepEqual(седьмой.всегда.map((с) => с.имя), ['Губин Илья', 'Алёшин Юрий', 'Баранец София']);
  assert.equal(седьмой.всегда.some((с) => с.classId !== '7a'), false, 'чужих в тройке класса нет');
});

test('в тройке класса не больше трёх', () => {
  const данные = {
    ...ДАННЫЕ,
    students: { ...ДАННЫЕ.students, s5: { name: 'Ким Лев', classId: '7a' } },
    leaderboard: {
      ...ДАННЫЕ.leaderboard,
      '7a': { ...ДАННЫЕ.leaderboard['7a'], s5: { xp: 1, weekId: НЕДЕЛЯ, weekXp: 1 } },
    },
  };
  const седьмой = собрать(данные).классы.find((к) => к.id === '7a');
  assert.equal(седьмой.всегда.length, 3);
});

/*
  Недельная строка живёт до конца недели, а потом устаревает: в базе у неё
  остаётся прошлый weekId. Не отсечь его — и в понедельник на табло висели
  бы прошлонедельные победители, которых уже никто не догоняет.
*/
test('в героях недели только строки текущей недели', () => {
  const { неделя } = собрать().школа;
  assert.deepEqual(неделя.map((с) => с.имя), ['Баранец София', 'Заец Алиса', 'Алёшин Юрий']);
  assert.equal(неделя.some((с) => с.имя === 'Губин Илья'), false, 'его строка — с прошлой недели');
});

test('нули в героях недели не показываются', () => {
  const данные = { ...ДАННЫЕ, leaderboard: { '7a': { s1: { hwXp: 10, weekId: НЕДЕЛЯ, hwWeekXp: 0 } } } };
  assert.deepEqual(собрать(данные).школа.неделя, []);
});

/*
  Решение учителя от 16 сентября 2026: в почёт идут только домашние работы.
  Тренажёр открыт всем и всегда, домашку задаёт учитель и сдаётся она один раз;
  считай общую сумму — и впереди окажется тот, у кого больше свободного времени.
*/
test('игры и тренажёр в таблицу почёта не идут', () => {
  const данные = {
    ...ДАННЫЕ,
    leaderboard: {
      '7a': {
        s1: { xp: 9000, hwXp: 0, weekId: НЕДЕЛЯ, weekXp: 9000, hwWeekXp: 0 },
        s2: { xp: 30, hwXp: 30, weekId: НЕДЕЛЯ, weekXp: 30, hwWeekXp: 30 },
      },
    },
  };
  const { всегда, неделя } = собрать(данные).школа;

  assert.deepEqual(всегда.map((с) => с.имя), ['Баранец София'], 'прошедший все игры мимо почёта');
  assert.deepEqual(неделя.map((с) => с.имя), ['Баранец София']);
});

test('в почёте стоит домашний счёт, а не общий', () => {
  const [первый] = собрать().школа.всегда;
  assert.equal(первый.имя, 'Губин Илья');
  assert.equal(первый.xp, 500, 'у него 800 общих и 500 домашних');
});

test('по каждому классу свой счёт и свои герои', () => {
  const классы = собрать().классы;
  const седьмой = классы.find((к) => к.id === '7a');

  assert.equal(седьмой.title, '7А');
  assert.deepEqual(седьмой.неделя.map((с) => с.имя), ['Баранец София', 'Алёшин Юрий']);
  // Задано: трое учеников на два заданных урока. Сдано — по числу сданных
  // работ, а не по урокам, пройденным в тренажёре (их у класса 12).
  assert.equal(седьмой.задано, 6);
  assert.equal(седьмой.сдано, 5);
  assert.equal(седьмой.процент, 83);
});

test('класс без заданных уроков не делит на ноль', () => {
  const данные = { ...ДАННЫЕ, assignments: {} };
  const седьмой = собрать(данные).классы.find((к) => к.id === '7a');
  assert.equal(седьмой.задано, 0);
  assert.equal(седьмой.процент, 0);
});

// Строку в таблице пишет сам ученик, и таблица открыта на чтение всем.
// Опираться на неё как на список — значит верить тому, что туда написали.
test('чужие строки в таблице на табло не попадают', () => {
  const данные = {
    ...ДАННЫЕ,
    leaderboard: { '7a': { ...ДАННЫЕ.leaderboard['7a'], 'самозванец': { xp: 9999, weekId: НЕДЕЛЯ, weekXp: 9999 } } },
  };
  const { всегда, неделя } = собрать(данные).школа;
  assert.equal(всегда.some((с) => с.xp === 9999), false);
  assert.equal(неделя.some((с) => с.xp === 9999), false);
});

test('пустая база даёт пустое табло, а не ошибку', () => {
  const пусто = собратьТабло({ неделя: НЕДЕЛЯ });
  assert.deepEqual(пусто.школа.всегда, []);
  assert.deepEqual(пусто.школа.неделя, []);
  assert.deepEqual(пусто.классы, []);
});

test('ученик без единого балла в списки не лезет', () => {
  const данные = { ...ДАННЫЕ, leaderboard: {} };
  assert.deepEqual(собрать(данные).школа.всегда, []);
  const седьмой = собрать(данные).классы.find((к) => к.id === '7a');
  assert.equal(седьмой.сдано, 0);
});
