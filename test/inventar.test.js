import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, access } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

import { loadInventar } from '../js/content.js';

/*
  Инвентарь лабораторных работ.

  Реестр `content/inventar.json` лежит отдельно от уроков: в файлах уроков
  оборудование осталось списком названий, и добавленный в реестр значок
  оживляет все работы сразу, без правки контента. Плата за это — названия
  должны совпадать слово в слово, и следит за этим здешняя проверка.

  Реестр делит предметы полки на две части:

  - `приборы` — у них есть значок, и узнают их по виду;
  - `без картинки` — образцы и вещества, у них значка нет намеренно. Луковица
    на полке никакой загадки не составляет, а что налито в склянку, читают по
    подписи, и в жизни тоже: две одинаковые склянки (йод и масло в работе про
    свойства организмов) не различить никак.

  Полка становится картинками, когда каждый её предмет назван хоть там, хоть
  там: значит, работу разобрали. Если предмет не назван нигде, полка целиком
  остаётся названиями — молча показать половину картинками худшее из двух.
*/

const ROOT = fileURLToPath(new URL('..', import.meta.url));

async function файлЕсть(...части) {
  try {
    await access(join(ROOT, ...части));
    return true;
  } catch {
    return false;
  }
}

/** Все полки инвентаря, какие есть в уроках. */
async function полки() {
  const dir = join(ROOT, 'content', 'lessons');
  const найдено = [];

  for (const файл of (await readdir(dir)).filter((ф) => ф.endsWith('.json'))) {
    const урок = JSON.parse(await readFile(join(dir, файл), 'utf8'));
    for (const блок of урок.summary?.blocks ?? []) {
      const набор = блок.run?.equipment;
      if (!набор) continue;
      найдено.push({
        урок: файл.replace('.json', ''),
        предметы: [...(набор.need ?? []), ...(набор.extra ?? [])],
      });
    }
  }
  return найдено;
}

const реестрФайл = JSON.parse(await readFile(join(ROOT, 'content', 'inventar.json'), 'utf8'));
const реестр = await loadInventar({
  fetchFn: async () => ({ ok: true, json: async () => реестрФайл }),
});
const всеПолки = await полки();
const наПолках = new Set(всеПолки.flatMap((п) => п.предметы));

test('у каждого значка есть файл рисунка и описание для читалки', async () => {
  const приборы = Object.entries(реестрФайл.приборы ?? {});
  assert.ok(приборы.length > 0, 'реестр пуст');

  for (const [название, запись] of приборы) {
    assert.ok(запись.рисунок, `${название}: не указан рисунок`);
    assert.ok(
      await файлЕсть('img', 'bio', запись.рисунок),
      `${название}: файла img/bio/${запись.рисунок} нет`,
    );
    // Прибор на полке не подписан, и для того, кто страницу слушает,
    // описание — единственный способ узнать, что на плитке.
    assert.ok(запись.alt?.length > 10, `${название}: нет внятного описания alt`);
  }
});

test('синонимы ведут на существующий прибор', () => {
  for (const [синоним, название] of Object.entries(реестрФайл['то же самое'] ?? {})) {
    assert.ok(реестрФайл.приборы?.[название], `«${синоним}» ведёт на неизвестный «${название}»`);
    assert.equal(
      реестр.значок(синоним)?.рисунок,
      реестрФайл.приборы[название].рисунок,
      `«${синоним}» не разложился в значок`,
    );
  }
});

test('предмет не назван и прибором, и образцом сразу', () => {
  const двойные = (реестрФайл['без картинки'] ?? []).filter(
    (имя) => реестрФайл.приборы?.[имя] || реестрФайл['то же самое']?.[имя],
  );
  assert.deepEqual(двойные, [], `названы дважды: ${двойные.join(', ')}`);
});

test('в реестре нет записей, которые нигде не нужны', () => {
  // Синоним считается использованием своего прибора: «Скальпель или нож» на
  // полке — это и есть скальпель.
  const через = реестрФайл['то же самое'] ?? {};
  const задействованы = new Set(наПолках);
  for (const [синоним, название] of Object.entries(через)) {
    if (наПолках.has(синоним)) задействованы.add(название);
  }

  const лишниеПриборы = Object.keys(реестрФайл.приборы ?? {}).filter(
    (имя) => !задействованы.has(имя),
  );
  const лишниеОбразцы = (реестрФайл['без картинки'] ?? []).filter((имя) => !наПолках.has(имя));

  assert.deepEqual(
    { приборы: лишниеПриборы, образцы: лишниеОбразцы },
    { приборы: [], образцы: [] },
    'записи есть, а работы их не просят — либо убрать, либо поставить в работу',
  );
});

test('все полки разобраны: каждый предмет назван прибором или образцом', () => {
  const беды = [];
  for (const полка of всеПолки) {
    const нет = полка.предметы.filter((имя) => !реестр.разобран(имя));
    if (нет.length) беды.push(`${полка.урок}: ${нет.join(', ')}`);
  }

  assert.deepEqual(
    беды,
    [],
    'предмет полки не назван в content/inventar.json — добавь его в «приборы» ' +
      'со значком либо в «без картинки», если это образец:\n  ' + беды.join('\n  '),
  );
});

test('на каждой полке есть хотя бы один прибор со значком', () => {
  // Полка из одних образцов картинками не станет, и это верно: узнавать по
  // виду там нечего. Но такой работы у нас нет, и появление её — повод
  // подумать, а не тихо откатиться к названиям.
  const беды = всеПолки
    .filter((п) => !п.предметы.some((имя) => реестр.значок(имя)))
    .map((п) => п.урок);

  assert.deepEqual(беды, [], `полка из одних образцов: ${беды.join(', ')}`);
});

test('«Наблюдение и эксперимент» собирается целиком по картинкам', () => {
  // Первая переведённая работа, и единственная, где образцов нет вовсе.
  // Проверка стережёт её отдельно: случайно убранный значок иначе тихо
  // вернул бы полку к названиям.
  const полка = всеПолки.find((п) => п.урок === '5-nablyudenie-i-eksperiment');
  assert.ok(полка, 'работа с полкой в этом уроке не нашлась');

  const без = полка.предметы.filter((имя) => !реестр.значок(имя));
  assert.deepEqual(без, [], `без значка остались: ${без.join(', ')}`);
});
